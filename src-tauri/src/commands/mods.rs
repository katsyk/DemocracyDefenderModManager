pub(crate) const MODS_DIRECTORY: &'static str = "mods/";
pub(crate) const MANIFEST_FILE: &'static str = "manifest.json";
const NO_PATCH_FILES_WARNING: &str = "no Helldivers 2 patch files found in this archive";

/// The JSON shape returned by every install command: a [`Mod`] plus an
/// optional, non-fatal warning (currently only "no Helldivers 2 patch files
/// found").
#[derive(Debug, Clone, Serialize)]
#[serde(rename_all = "PascalCase")]
pub struct InstalledMod {
    #[serde(flatten)]
    pub r#mod: Mod,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub warning: Option<String>,
}

/// A manifest counts as "generated by us" (as opposed to one an author
/// shipped) exactly when it's the `LOCAL`-prefixed legacy manifest
/// `generate_local_manifest` produces. Only those are safe to rewrite with
/// an auto-detected `Options` list -- an author's own manifest.json is
/// never touched.
fn is_local_generated(manifest: &Manifest) -> bool {
    matches!(manifest, Manifest::Legacy(m) if m.guid.as_bytes().get(..5) == Some(b"LOCAL"))
}

/// After extraction/copy, if (and only if) the manifest was generated by us
/// because the mod shipped no `manifest.json` of its own, look for where
/// the actual Helldivers 2 patch files ended up and, if they're not at the
/// mod root, fill in `Options` (persisting the rewritten manifest.json) so
/// deploy and the existing option picker find them without any further
/// user action. Returns a non-fatal warning if no patch files were found
/// anywhere.
async fn apply_patch_layout(mod_dir: &Path, manifest: &mut Manifest) -> anyhow::Result<Option<String>> {
    if !is_local_generated(manifest) {
        return Ok(None);
    }

    let layout = detect_patch_layout(mod_dir).await?;

    match layout {
        PatchLayout::RootHasFiles => Ok(None),
        PatchLayout::Options(paths) => {
            if let Manifest::Legacy(legacy) = manifest {
                legacy.options = Some(paths);
            }
            let manifest_file = mod_dir.join(MANIFEST_FILE);
            let data = serde_json::to_vec_pretty(manifest)?;
            tokio::fs::write(manifest_file, data).await?;
            Ok(None)
        }
        PatchLayout::NoneFound => {
            let nested = find_nested_archives(mod_dir).await;
            if nested.is_empty() {
                Ok(Some(NO_PATCH_FILES_WARNING.to_string()))
            } else {
                Ok(Some(format!(
                    "{NO_PATCH_FILES_WARNING}. It contains other archives ({}): it's probably a pack of several \
                     versions or parts. Extract the one you want with 7-Zip and add that to DDMM instead.",
                    nested.join(", ")
                )))
            }
        }
    }
}

/// Up to five archive files anywhere in `dir` (a few levels deep): a mod
/// that ships its variants as archives inside the archive. They are never
/// unpacked automatically (an archive inside an archive is also the
/// classic way to sneak past size and path checks); the warning names them
/// so the user knows what to do.
async fn find_nested_archives(dir: &Path) -> Vec<String> {
    let mut found = Vec::new();
    let mut stack = vec![(dir.to_path_buf(), 0usize)];
    while let Some((current, depth)) = stack.pop() {
        let Ok(mut entries) = tokio::fs::read_dir(&current).await else { continue };
        while let Ok(Some(entry)) = entries.next_entry().await {
            let Ok(file_type) = entry.file_type().await else { continue };
            let name = entry.file_name().to_string_lossy().into_owned();
            if file_type.is_dir() && depth < 4 {
                stack.push((entry.path(), depth + 1));
            } else if file_type.is_file()
                && crate::commands::handoff::ARCHIVE_SUFFIXES.iter().any(|s| name.to_ascii_lowercase().ends_with(s))
            {
                found.push(name);
            }
        }
    }
    found.sort_by(|a, b| crate::utils::natural_cmp(a, b));
    found.truncate(5);
    found
}

#[allow(dead_code)]
trait ZipResult<S, E, T> {
    fn zip(self, other: Result<T, E>) -> Result<(S, T), E>;
    fn zip_value(self, other: T) -> Result<(S, T), E>;
}

impl<S, E, T> ZipResult<S, E, T> for Result<S, E> {
    fn zip(self, other: Result<T, E>) -> Result<(S, T), E> {
        match (self, other) {
            (Ok(a), Ok(b)) => Ok((a, b)),
            (Err(e), Ok(_)) => Err(e),
            (Ok(_), Err(e)) => Err(e),
            (Err(e), Err(_)) => Err(e),
        }
    }

    fn zip_value(self, other: T) -> Result<(S, T), E> {
        match self {
            Ok(s) => Ok((s, other)),
            Err(e) => Err(e)
        }
    }
}

/// Resolve an image path from a mod's manifest (`IconPath`, an option's
/// `Image`) to the file on disk, with the same rules as deploy
/// ([`crate::utils::fix_path_casing`]: `\` separators, any casing, never
/// outside the mod folder). `None` when there's no such file, so the UI
/// shows its default icon. Only answers for folders inside `mods/`.
pub(crate) async fn resolve_mod_image_path(base_path: &Path, mod_directory: &Path, image: &str) -> Option<PathBuf> {
    let mods_root = tokio::fs::canonicalize(base_path.join(MODS_DIRECTORY)).await.ok()?;
    let mod_dir = tokio::fs::canonicalize(mod_directory).await.ok()?;
    if !mod_dir.starts_with(&mods_root) || mod_dir == mods_root {
        return None;
    }
    let relative = crate::utils::fix_path_casing(&mod_dir, Path::new(image)).await.ok()?;
    if relative.as_os_str().is_empty() {
        return None;
    }
    // Hand back the path as the app knows it (not the canonical form, which
    // is `\\?\C:\…` on Windows); the asset scope allows both.
    let file = mod_directory.join(relative);
    tokio::fs::metadata(&file).await.ok().filter(|m| m.is_file()).map(|_| file)
}

#[tauri::command]
pub async fn resolve_mod_image(
    state: State<'_, AppState>,
    mod_directory: PathBuf,
    image: String,
) -> TAResult<Option<PathBuf>> {
    Ok(resolve_mod_image_path(&state.base_path, &mod_directory, &image).await)
}

#[tauri::command]
pub async fn get_mods(state: State<'_, AppState>) -> TAResult<Vec<Mod>> {
    let mut state_mods = state.mods.lock().await;
    log::info!("Loading mods...");
    let mods = ensure_mods_loaded(&mut state_mods, &state.base_path).await?;
    Ok(mods.clone())
}

/// Read every installed mod from disk into `state_mods` the first time it's
/// needed (a no-op once loaded) and return it. Shared by `get_mods` and by
/// the browser bridge, which can receive an install before the frontend
/// has ever called `get_mods` -- e.g. a first run still on the Settings
/// page, or DDMM just launched by the native-messaging host.
pub(crate) async fn ensure_mods_loaded<'a>(
    state_mods: &'a mut Option<Vec<Mod>>,
    base_path: &Path,
) -> TAResult<&'a mut Vec<Mod>> {
    if state_mods.is_some() {
        log::debug!("Mods already loaded.");
        return Ok(state_mods.as_mut().unwrap());
    }

    let mods_dir = base_path.join(MODS_DIRECTORY);
    let mut mods = Vec::new();
    if !mods_dir.is_dir() {
        // First run: nothing installed yet. Still record the (empty) list
        // as loaded, or every install command would fail with "mods not
        // read" until something called get_mods a second time.
        tokio::fs::create_dir_all(&mods_dir).await.into_ta_result()?;
    } else {
        recover_leftover_folders(&mods_dir).await;

        let mut mods_dir = tokio::fs::read_dir(mods_dir).await.into_ta_result()?;
        while let Some(entry) = mods_dir.next_entry().await.into_ta_result()? {
            let mod_dir = entry.path();

            // Folders starting with a dot are DDMM's own working folders
            // (an update's staging copy or the old version set aside
            // during one), never mods: loading one would list a mod twice.
            if is_hidden_name(&entry.file_name()) {
                log::debug!("Skipping working folder {:?}.", mod_dir);
                continue;
            }

            let manifest_file = mod_dir.join(MANIFEST_FILE);
            if !manifest_file.is_file() {
                continue;
            }

            // One unreadable manifest must not take the whole library down
            // with it (every later install would then fail with "mods not
            // read"): log it with the reason and skip that mod.
            let manifest = match tokio::fs::read(&manifest_file).await {
                Ok(data) => Manifest::parse(&data, &manifest_file.to_string_lossy()),
                Err(e) => Err(anyhow::anyhow!("can't read {:?}: {}", manifest_file, e)),
            };
            let manifest = match manifest {
                Ok(m) => m,
                Err(e) => {
                    log::error!("Skipping mod in {:?}: {:#}", mod_dir, e);
                    continue;
                }
            };

            let mut r#mod = Mod {
                manifest,
                directory: mod_dir,
                sources: Vec::new(),
            };
            if let Err(e) = r#mod.normalize_paths().await {
                log::error!("Path normalization failed for {:?}: {:#}", r#mod.directory, e);
            }
            r#mod.resolve_sources().await;

            mods.push(r#mod);
        }
    }

    log::info!("Mods loaded.");
    Ok(state_mods.insert(mods))
}

#[tauri::command]
pub async fn delete_mod(state: State<'_, AppState>, guid: Uuid) -> TAResult<()> {
    let _data_op = state.data_op().into_ta_result()?;
    let mut mods = state.mods.lock().await;
    if mods.is_none() {
        return anyhow::anyhow!("mods not read").into_ta_result();
    }
    let mods = mods.as_mut().unwrap();

    log::info!("Deleting mod \"{}\"...", guid);

    if let Some(i) = mods.iter().position(|m| m.guid() == guid) {
        let mods_root = state.base_path.join(MODS_DIRECTORY);
        // Checked before the mod leaves the list, so a refused delete
        // doesn't leave a mod that silently comes back on the next launch.
        mod_folder::ensure_mod_folder(&mods_root, &mods[i].directory).into_ta_result()?;
        let r#mod = mods.remove(i);
        log::info!("Mod removed form registry.");

        log::info!("Deleting files...");
        mod_folder::remove_mod_folder(&mods_root, &r#mod.directory).await.into_ta_result()?;

        log::info!("Mod deletion complete.");
        Ok(())
    } else {
        anyhow_tauri::bail!("mod with GUID {{{}}} not found", guid);
    }
}

#[tauri::command]
pub async fn add_mod(state: State<'_, AppState>, archive_file: PathBuf) -> TAResult<InstalledMod> {
    let _data_op = state.data_op().into_ta_result()?;
    let mut mods = state.mods.lock().await;
    if mods.is_none() {
        return anyhow::anyhow!("mods not read").into_ta_result();
    }
    let mods = mods.as_mut().unwrap();

    let (r#mod, warning) = install_from_archive(&state, mods, &archive_file).await?;
    Ok(InstalledMod { r#mod, warning })
}

/// Shared core of `add_mod`: prepares the mod directory, resolves the
/// manifest (from the archive if present, generating a local one
/// otherwise), extracts, and registers the mod.
///
/// Takes the already-locked mods vector rather than `State` directly so it
/// can be called both from a `#[tauri::command]` that holds the lock for a
/// single install, and from callers (like `add_paths`) that lock once per
/// item without ever calling back into another `#[tauri::command]` while
/// holding the mutex.
///
/// The mod's folder is named after the archive (made safe and unique, see
/// [`prepare_mod_dir`]); a generated manifest (the
/// archive ships none) gets a readable name from the file name instead,
/// without Nexus Mods' download suffix (see
/// [`crate::mod_import::display_name_from_file`]), and a Nexus download's
/// page and version are recorded (see [`record_nexus_from_file_name`]).
pub(crate) async fn install_from_archive(state: &AppState, mods: &mut Vec<Mod>, archive_file: &Path) -> TAResult<(Mod, Option<String>)> {
    log::debug!("Obtaining name...");
    let dir_name = archive_file
        .file_stem()
        .ok_or(anyhow::anyhow!("archive path has no file name"))?
        .to_str()
        .map(str::to_string)
        .ok_or(anyhow::anyhow!("file name conversion failed"))?;
    let file_name = archive_file.file_name().and_then(|n| n.to_str()).unwrap_or(&dir_name).to_string();
    let display_name = crate::mod_import::display_name_from_file(&file_name, true);

    log::info!("Adding mod from {:?}...", archive_file);
    let subject = subject_of(archive_file);
    let (mut r#mod, warning) =
        install_archive_steps(&state.base_path, mods, archive_file, &dir_name, &display_name, &subject)
            .await
            .map_err(report)?;
    record_nexus_from_file_name(mods, &mut r#mod, &file_name, true).await;
    Ok((r#mod, warning))
}

/// A mod just installed from a file Nexus Mods named (`Name-1234-1-0-...`)
/// gets that Nexus page, version and file recorded in its origin sidecar,
/// the same way import records them, so "Check for updates" works for it.
/// Read off the file name only: no Nexus API call.
///
/// Skipped when the mod already has an origin sidecar, or when its own
/// manifest names a different Nexus page. Callers that know where the file
/// came from (Add from URL, browser installs) write their origin afterwards,
/// which replaces this one: a download URL's attribution always wins.
async fn record_nexus_from_file_name(mods: &mut [Mod], r#mod: &mut Mod, file_name: &str, is_archive: bool) {
    let Some(nexus) = crate::mod_import::nexus_ref_from_name(file_name, is_archive) else { return };
    let other_page = r#mod.sources.iter().any(|s| {
        s.provider.eq_ignore_ascii_case("nexus")
            && s.origin == sources::SourceOrigin::Manifest
            && sources::resolved_source_id(s).is_some_and(|id| id != nexus.mod_id)
    });
    if other_page || sources::load_origin_sidecar(&r#mod.directory).await.is_some() {
        return;
    }
    let mut sidecar = sources::OriginSidecar {
        sources: Vec::new(),
        installed_at: std::time::SystemTime::now().duration_since(std::time::UNIX_EPOCH).map(|d| d.as_secs()).unwrap_or(0),
        installed_files: Vec::new(),
        skipped_versions: Vec::new(),
        imported_archive: None,
    };
    crate::mod_import::add_nexus_to_sidecar(&mut sidecar, &nexus, r#mod);
    if sidecar.sources.is_empty() && sidecar.installed_files.is_empty() {
        return;
    }
    if let Err(e) = sources::save_origin_sidecar(&r#mod.directory, &sidecar).await {
        log::error!("Failed to record the Nexus Mods source: {}", e);
        return;
    }
    r#mod.resolve_sources().await;
    if let Some(existing) = mods.iter_mut().find(|m| m.guid() == r#mod.guid()) {
        *existing = r#mod.clone();
    }
}

/// [`install_from_archive`] named `name` (the generated manifest's name
/// when the archive ships none, and -- made safe and unique by
/// [`prepare_mod_dir`] -- its folder's name) instead of after the archive
/// -- used by the bulk import, which picks a readable, unique name itself.
pub(crate) async fn install_from_archive_as(
    base_path: &Path,
    mods: &mut Vec<Mod>,
    archive_file: &Path,
    name: &str,
) -> TAResult<(Mod, Option<String>)> {
    log::info!("Adding mod from {:?}...", archive_file);
    let subject = subject_of(archive_file);
    install_archive_steps(base_path, mods, archive_file, name, name, &subject).await.map_err(report)
}

/// Log a failed install (the whole message: which mod, which step, why)
/// and hand it to the frontend unchanged.
fn report(e: InstallError) -> anyhow_tauri::TACommandError {
    log::error!("{e}");
    anyhow_tauri::TACommandError(anyhow::Error::new(e))
}

async fn install_archive_steps(
    base_path: &Path,
    mods: &mut Vec<Mod>,
    archive_file: &Path,
    dir_name: &str,
    manifest_name: &str,
    subject: &str,
) -> Result<(Mod, Option<String>), InstallError> {
    log::debug!("Opening archive...");
    let archive = Archive::open(archive_file).install_step(subject, InstallStep::OpenArchive)?;

    log::info!("Preparing mod directory...");
    let mods_root = base_path.join(MODS_DIRECTORY);
    let (mod_dir, folder_name) = prepare_mod_dir(archive_file, &mods_root, dir_name, subject).await?;
    let manifest_name = display_name(manifest_name, &folder_name);
    let manifest_file = mod_dir.join(MANIFEST_FILE);

    // From here on `mod_dir` is ours (prepare_mod_dir just created it), so
    // a failure must remove it again: a half-written directory with a
    // manifest.json would otherwise show up as an empty "ghost" mod on the
    // next launch and block retrying the same file with "mod directory
    // already exists" (e.g. after an archive was rejected as unsafe).
    let prepared: Result<(Mod, Option<String>), InstallError> = async {
        log::info!("Resolving manifest...");
        let (archive, manifest) = resolve_manifest(archive, manifest_name.to_string(), manifest_file.clone())
            .await
            .map_err(|e| manifest_failure(subject, e))?;

        let mut r#mod = Mod {
            manifest,
            directory: mod_dir.clone(),
            sources: Vec::new(),
        };

        log::info!("Checking for duplicate...");
        check_not_installed(mods, &r#mod, subject)?;

        log::info!("Extracting archive...");
        extract_archive(archive, mod_dir.clone()).await.install_step(subject, InstallStep::Extract)?;

        log::debug!("Detecting patch file layout...");
        let warning = apply_patch_layout(&mod_dir, &mut r#mod.manifest)
            .await
            .install_step(subject, InstallStep::FindPatchFiles)?;
        Ok((r#mod, warning))
    }
    .await;
    let (mut r#mod, warning) = match prepared {
        Ok(v) => v,
        Err(e) => {
            if let Err(cleanup) = mod_folder::remove_mod_folder(&mods_root, &mod_dir).await {
                log::error!("Failed to clean up {:?} after a failed install: {:#}", mod_dir, cleanup);
            }
            return Err(e);
        }
    };

    log::debug!("Normalizing paths...");
    if let Err(e) = r#mod.normalize_paths().await {
        log::error!("Path normalization failed: {}", e);
    }

    r#mod.resolve_sources().await;

    mods.push(r#mod.clone());
    log::info!("Mod successfully added.");
    Ok((r#mod, warning))
}

/// Reading the manifest out of an archive fails either because the
/// archive can't be read (encrypted, damaged, an unsupported method: an
/// extraction problem) or because the manifest itself is broken.
fn manifest_failure(subject: &str, e: anyhow::Error) -> InstallError {
    let step = if crate::archive::is_archive_problem(&e) { InstallStep::Extract } else { InstallStep::ReadManifest };
    InstallError::new(subject, step, e)
}

/// Refuse a mod whose GUID is already in the mod list, saying which mod
/// has it and what to do: the same mod again, or -- when the names differ
/// -- a different mod whose author reused another mod's manifest.json.
fn check_not_installed(mods: &[Mod], new: &Mod, subject: &str) -> Result<(), InstallError> {
    let Some(existing) = mods.iter().find(|m| m.guid() == new.guid()) else {
        return Ok(());
    };
    let cause = anyhow::anyhow!(
        "its manifest.json gives it the ID (GUID) {{{}}}, and \"{}\" in your mod list already has that ID",
        new.guid(),
        existing.name()
    );
    let hint = if existing.name().trim().eq_ignore_ascii_case(new.name().trim()) {
        format!(
            "\"{}\" is already installed. To replace it with this file, remove it first (or use Update on it).",
            existing.name()
        )
    } else {
        format!(
            "Two different mods can't share an ID: the mod's author probably copied another mod's manifest.json, \
             so let them know. To install it anyway, remove \"{}\" first, or extract this archive, delete its \
             manifest.json, and add the extracted folder with Add Folder (DDMM then gives it an ID of its own).",
            existing.name()
        )
    };
    Err(InstallError::new(subject, InstallStep::Register, cause).with_hint(hint))
}

#[tauri::command]
pub async fn add_mods(state: State<'_, AppState>, archive_files: Vec<PathBuf>) -> TAResult<Vec<TAResult<InstalledMod>>> {
    let _data_op = state.data_op().into_ta_result()?;
    let mut mods = state.mods.lock().await;
    if mods.is_none() {
        return anyhow::anyhow!("mods not read").into_ta_result();
    }
    let mods = mods.as_mut().unwrap();

    log::info!("Adding {} mod(s)...", archive_files.len());

    // One after another through the single-archive install, so every file
    // gets exactly the same checks, cleanup and error messages as Add; a
    // failure only affects its own file.
    let mut results = Vec::with_capacity(archive_files.len());
    for archive_file in &archive_files {
        let result = install_from_archive(&state, mods, archive_file).await;
        log::info!(" - {:?} : {}", archive_file, if result.is_ok() { "Ok" } else { "Err" });
        results.push(result.map(|(r#mod, warning)| InstalledMod { r#mod, warning }));
    }

    Ok(results)
}

/// Create a new, empty folder in `mods_root` to install `source` (an
/// archive file or a folder) into, and return it with its name.
///
/// The name is `wanted` made safe with [`mod_folder::safe_folder_name`]
/// (so `.`, `..`, separators, reserved names and the like can never name
/// anything but a single new folder), or -- when a file or folder of that
/// name is already there -- `wanted (2)`, `wanted (3)`, ... An existing
/// folder is never deleted or reused: it may be another mod, or something
/// the user put there by hand.
///
/// Refuses first if `source` and the folder overlap -- copying into it
/// would then copy the source into itself.
async fn prepare_mod_dir(
    source: &Path,
    mods_root: &Path,
    wanted: &str,
    subject: &str,
) -> Result<(PathBuf, String), InstallError> {
    let step = InstallStep::PrepareFolder;
    tokio::fs::create_dir_all(mods_root).await.install_step(subject, step)?;
    let base = mod_folder::safe_folder_name(wanted);
    for n in 1..=10_000usize {
        let name = if n == 1 { base.clone() } else { mod_folder::numbered(&base, n) };
        let mod_dir = mods_root.join(&name);
        mod_folder::ensure_mod_folder(mods_root, &mod_dir).install_step(subject, step)?;
        if crate::fs_util::path_overlap(source, &mod_dir).install_step(subject, step)?.is_some() {
            return Err(InstallError::new(
                subject,
                step,
                anyhow::anyhow!(
                    "it is inside (or is) the folder DDMM would install it into ({:?})",
                    mod_dir
                ),
            )
            .with_hint("Move it somewhere outside DDMM's mod storage and add it from there."));
        }
        // `create_dir`, not `create_dir_all`: it fails if the folder is
        // already there, so nothing that exists is ever taken over.
        match tokio::fs::create_dir(&mod_dir).await {
            Ok(()) => return Ok((mod_dir, name)),
            Err(e) if e.kind() == std::io::ErrorKind::AlreadyExists => {
                log::info!("{:?} already exists; leaving it alone and trying the next free name.", mod_dir);
            }
            Err(e) => return Err(InstallError::new(subject, step, e)),
        }
    }
    Err(InstallError::new(
        subject,
        step,
        anyhow::anyhow!("no free folder name for \"{}\" in DDMM's mod storage", base),
    ))
}

/// The name a mod without a manifest.json is listed under: the name it was
/// added as, unless nothing readable is left of that (such as a file called
/// `..zip`), in which case its folder's name.
fn display_name(wanted: &str, folder_name: &str) -> String {
    let trimmed = wanted.trim_matches(|c: char| c == '.' || c.is_whitespace());
    if trimmed.is_empty() { folder_name.to_string() } else { wanted.trim().to_string() }
}

/// Whether a folder in the mod storage is one of DDMM's hidden working
/// folders (its name starts with a dot) rather than a mod.
fn is_hidden_name(name: &std::ffi::OsStr) -> bool {
    name.to_string_lossy().starts_with('.')
}

/// Generate the same "no manifest present" local legacy manifest, whether
/// the mod came from an archive with no `manifest.json`, or a plain folder
/// with no `manifest.json`.
fn generate_local_manifest(name: String) -> anyhow::Result<Manifest> {
    let mut guid = [0u8; 16];
    guid[..5].copy_from_slice(b"LOCAL");
    SysRng.try_fill_bytes(&mut guid[5..])?;

    Ok(Manifest::Legacy(legacy::Manifest {
        guid: Uuid::from_bytes(guid),
        name,
        description: String::new(),
        icon_path: None,
        options: None,
    }))
}

async fn resolve_manifest(mut archive: Archive, name: String, manifest_file: PathBuf) -> anyhow::Result<(Archive, Manifest)> {
    if let Some(entry) = archive.find_root_file_ci(MANIFEST_FILE)? {
        let manifest_data = archive.read_path(&entry)?;
        let manifest = Manifest::parse(&manifest_data, &entry.to_string_lossy())?;
        Ok((archive, manifest))
    } else {
        let manifest = generate_local_manifest(name)?;

        let manifest_data = serde_json::to_vec_pretty(&manifest)?;
        tokio::fs::write(&manifest_file, manifest_data)
            .await
            .with_context(|| format!("couldn't write {:?}", manifest_file))?;

        Ok((archive, manifest))
    }
}

/// Same idea as [`resolve_manifest`], but for a plain folder install: read
/// `manifest.json` from the source folder if present, otherwise generate a
/// local one and write it straight into the (already-created) destination
/// mod directory.
async fn resolve_manifest_for_dir(source_dir: &Path, name: String, manifest_file: PathBuf) -> anyhow::Result<Manifest> {
    let source_manifest = find_manifest_file(source_dir).await;
    if let Some(source_manifest) = source_manifest {
        let manifest_data = tokio::fs::read(&source_manifest)
            .await
            .with_context(|| format!("couldn't read {:?}", source_manifest))?;
        let manifest = Manifest::parse(&manifest_data, &source_manifest.to_string_lossy())?;
        Ok(manifest)
    } else {
        let manifest = generate_local_manifest(name)?;

        let manifest_data = serde_json::to_vec_pretty(&manifest)?;
        tokio::fs::write(&manifest_file, manifest_data)
            .await
            .with_context(|| format!("couldn't write {:?}", manifest_file))?;

        Ok(manifest)
    }
}

async fn extract_archive(mut archive: Archive, mod_dir: PathBuf) -> anyhow::Result<()> {
    let dir = mod_dir.clone();
    tokio::task::spawn_blocking(move || archive.extract_to(dir)).await??;
    normalize_manifest_file_name(&mod_dir).await
}

/// `dir`'s manifest file: `manifest.json`, or failing that a case variant
/// such as `Manifest.json` (fine on Windows, invisible to an exact lookup
/// on Linux's case-sensitive filesystems).
async fn find_manifest_file(dir: &Path) -> Option<PathBuf> {
    let exact = dir.join(MANIFEST_FILE);
    if exact.is_file() {
        return Some(exact);
    }
    let mut entries = tokio::fs::read_dir(dir).await.ok()?;
    while let Ok(Some(entry)) = entries.next_entry().await {
        if entry.file_name().to_string_lossy().eq_ignore_ascii_case(MANIFEST_FILE)
            && entry.file_type().await.map(|t| t.is_file()).unwrap_or(false)
        {
            return Some(entry.path());
        }
    }
    None
}

/// After extracting/copying a mod, rename a `Manifest.json`-style case
/// variant to exactly `manifest.json`, which is what loading the library
/// looks for -- otherwise, on Linux, the mod would disappear on restart.
async fn normalize_manifest_file_name(mod_dir: &Path) -> anyhow::Result<()> {
    let exact = mod_dir.join(MANIFEST_FILE);
    if exact.is_file() {
        return Ok(());
    }
    if let Some(variant) = find_manifest_file(mod_dir).await {
        log::info!("Renaming {:?} to {:?}", variant, exact);
        crate::fs_util::move_path(&variant, &exact).await?;
    }
    Ok(())
}

/// Install a mod from a plain, already-unpacked folder: `folder` becomes the
/// mod's source, its `manifest.json` is used if present (otherwise a local
/// one is generated), and its contents are copied (not moved, symlinks not
/// followed) into the managed mod directory.
///
/// `folder` must not overlap DDMM's own mod storage (`<data>/mods`), which
/// is checked before anything on disk is touched:
/// - the storage folder itself, a folder containing it (such as DDMM's data
///   folder in a portable install), or a folder deeper inside an installed
///   mod is refused with an explanation -- copying any of those would copy
///   the folder into itself, over and over, until the disk is full;
/// - a mod folder sitting directly in the storage folder is adopted in
///   place ([`adopt_folder_in_place`]): nothing is copied, it just gets a
///   manifest and joins the mod list.
///
/// Mirrors [`install_from_archive`]'s locking contract: takes the
/// already-locked mods vector, never locks anything itself.
async fn install_from_folder(base_path: &Path, mods: &mut Vec<Mod>, folder: &Path) -> TAResult<(Mod, Option<String>)> {
    let (mut r#mod, warning) = install_from_folder_as(base_path, mods, folder, None).await?;
    let folder_name = crate::fs_util::resolve_path(folder)
        .ok()
        .and_then(|p| p.file_name().and_then(|n| n.to_str()).map(str::to_string));
    if let Some(folder_name) = folder_name {
        record_nexus_from_file_name(mods, &mut r#mod, &folder_name, false).await;
    }
    Ok((r#mod, warning))
}

/// [`install_from_folder`], optionally into `mods/<name>` instead of a
/// folder named after the source folder (the bulk import picks unique
/// names itself).
pub(crate) async fn install_from_folder_as(
    base_path: &Path,
    mods: &mut Vec<Mod>,
    folder: &Path,
    name_override: Option<&str>,
) -> TAResult<(Mod, Option<String>)> {
    log::info!("Adding mod from folder {:?}...", folder);
    let subject = subject_of(folder);
    install_folder_steps(base_path, mods, folder, name_override, &subject).await.map_err(report)
}

async fn install_folder_steps(
    base_path: &Path,
    mods: &mut Vec<Mod>,
    folder: &Path,
    name_override: Option<&str>,
    subject: &str,
) -> Result<(Mod, Option<String>), InstallError> {
    let refuse = |cause: anyhow::Error| InstallError::new(subject, InstallStep::PrepareFolder, cause);

    if !folder.is_dir() {
        return Err(refuse(anyhow::anyhow!("{:?} is not a folder (or no longer exists)", folder)));
    }

    let mods_root = base_path.join(MODS_DIRECTORY);
    let resolved = crate::fs_util::resolve_path(folder).install_step(subject, InstallStep::PrepareFolder)?;

    let name = resolved
        .file_name()
        .and_then(|n| n.to_str())
        .map(str::to_string)
        .ok_or_else(|| refuse(anyhow::anyhow!("the folder's name can't be read")))?;

    use crate::fs_util::{path_overlap, PathOverlap};
    match path_overlap(&resolved, &mods_root).install_step(subject, InstallStep::PrepareFolder)? {
        None => {}
        Some(PathOverlap::Same) => {
            return Err(refuse(anyhow::anyhow!(
                "That folder is DDMM's own mod storage ({}), so there is nothing to copy. \
                 Mods in it that have a manifest.json are already in your mod list. To add a \
                 mod folder that is in there without one, pick that mod's own folder instead: \
                 DDMM will set it up where it is, without copying it.",
                mods_root.display()
            )));
        }
        Some(PathOverlap::SecondInsideFirst) => {
            return Err(refuse(anyhow::anyhow!(
                "DDMM can't add {}: DDMM's own mod storage ({}) is inside it, so adding it would \
                 copy the folder into itself. Pick a single mod's folder instead.",
                folder.display(),
                mods_root.display()
            )));
        }
        Some(PathOverlap::FirstInsideSecond) => {
            let directly_in_storage = resolved
                .parent()
                .map(|parent| matches!(path_overlap(parent, &mods_root), Ok(Some(PathOverlap::Same))))
                .unwrap_or(false);
            if directly_in_storage && name_override.is_none() {
                if name.starts_with('.') {
                    return Err(refuse(anyhow::anyhow!(
                        "folders in DDMM's mod storage whose names start with a dot are DDMM's own working \
                         folders (for example a copy left behind by an interrupted update), not mods"
                    ))
                    .with_hint("Rename the folder so its name doesn't start with a dot, then add it again."));
                }
                let display_name = crate::mod_import::display_name_from_file(&name, false);
                return adopt_folder_in_place(mods, &mods_root.join(&name), &display_name, subject).await;
            }
            return Err(refuse(anyhow::anyhow!(
                "{} is inside a mod folder in DDMM's mod storage ({}). Pick that mod's own \
                 folder (the one directly inside the storage folder), or a folder outside it.",
                folder.display(),
                mods_root.display()
            )));
        }
    }

    // The folder keeps the source folder's name; a generated manifest gets
    // a readable one (no Nexus download suffix).
    let manifest_name = name_override
        .map(str::to_string)
        .unwrap_or_else(|| crate::mod_import::display_name_from_file(&name, false));
    let name = name_override.map(str::to_string).unwrap_or(name);
    log::info!("Preparing mod directory...");
    let (mod_dir, folder_name) = prepare_mod_dir(folder, &mods_root, &name, subject).await?;
    let manifest_name = display_name(&manifest_name, &folder_name);
    let manifest_file = mod_dir.join(MANIFEST_FILE);

    // From here on `mod_dir` is a folder we just created (and, per the
    // checks above, not the source or anywhere near it), so a failure must
    // remove it again rather than leave a half-copied mod behind.
    let result = install_from_folder_inner(mods, folder, &manifest_name, &mod_dir, &manifest_file, subject).await;

    if result.is_err() {
        if let Err(cleanup) = mod_folder::remove_mod_folder(&mods_root, &mod_dir).await {
            log::error!("Failed to clean up {:?} after a failed install: {:#}", mod_dir, cleanup);
        }
    }

    result
}

/// Register a folder that already sits directly in DDMM's mod storage as a
/// mod, without copying it: its own `manifest.json` is used if it has one,
/// otherwise a local one is generated and written into it (and removed
/// again if registering fails). Nothing else in the folder is touched, and
/// the folder is never deleted.
async fn adopt_folder_in_place(
    mods: &mut Vec<Mod>,
    mod_dir: &Path,
    name: &str,
    subject: &str,
) -> Result<(Mod, Option<String>), InstallError> {
    use crate::fs_util::{path_overlap, PathOverlap};

    log::info!("{:?} is already in the mod storage; adopting it in place.", mod_dir);

    if let Some(existing) = mods
        .iter()
        .find(|m| matches!(path_overlap(&m.directory, mod_dir), Ok(Some(PathOverlap::Same))))
    {
        return Err(InstallError::new(
            subject,
            InstallStep::Register,
            anyhow::anyhow!("\"{}\" is already installed (it's in your mod list)", existing.name()),
        ));
    }

    let manifest_file = mod_dir.join(MANIFEST_FILE);
    let had_manifest = find_manifest_file(mod_dir).await.is_some();

    let result: Result<(Mod, Option<String>), InstallError> = async {
        let manifest = resolve_manifest_for_dir(mod_dir, name.to_string(), manifest_file.clone())
            .await
            .install_step(subject, InstallStep::ReadManifest)?;
        let mut r#mod = Mod {
            manifest,
            directory: mod_dir.to_path_buf(),
            sources: Vec::new(),
        };

        check_not_installed(mods, &r#mod, subject)?;

        normalize_manifest_file_name(mod_dir).await.install_step(subject, InstallStep::ReadManifest)?;
        let warning = apply_patch_layout(mod_dir, &mut r#mod.manifest)
            .await
            .install_step(subject, InstallStep::FindPatchFiles)?;
        Ok((r#mod, warning))
    }
    .await;

    let (mut r#mod, warning) = match result {
        Ok(v) => v,
        Err(e) => {
            if !had_manifest {
                let _ = tokio::fs::remove_file(&manifest_file).await;
            }
            return Err(e);
        }
    };

    if let Err(e) = r#mod.normalize_paths().await {
        log::error!("Path normalization failed: {}", e);
    }
    r#mod.resolve_sources().await;

    mods.push(r#mod.clone());
    log::info!("Mod adopted in place.");
    Ok((r#mod, warning))
}

async fn install_from_folder_inner(
    mods: &mut Vec<Mod>,
    folder: &Path,
    name: &str,
    mod_dir: &Path,
    manifest_file: &Path,
    subject: &str,
) -> Result<(Mod, Option<String>), InstallError> {
    log::info!("Resolving manifest...");
    let manifest = resolve_manifest_for_dir(folder, name.to_string(), manifest_file.to_path_buf())
        .await
        .install_step(subject, InstallStep::ReadManifest)?;

    let mut r#mod = Mod {
        manifest,
        directory: mod_dir.to_path_buf(),
        sources: Vec::new(),
    };

    log::info!("Checking for duplicate...");
    check_not_installed(mods, &r#mod, subject)?;

    log::info!("Copying folder contents...");
    copy_dir_recursive(folder, mod_dir, &[sources::ORIGIN_SIDECAR_FILE])
        .await
        .map_err(|e| {
            // Same plain-language treatment as an archive's I/O errors
            // (disk full, access denied, path too long).
            match e.downcast::<std::io::Error>() {
                Ok(io) => crate::archive::io_error(io, "copying a file failed"),
                Err(e) => e,
            }
        })
        .install_step(subject, InstallStep::Copy)?;
    normalize_manifest_file_name(mod_dir).await.install_step(subject, InstallStep::Copy)?;

    log::debug!("Detecting patch file layout...");
    let warning = apply_patch_layout(mod_dir, &mut r#mod.manifest)
        .await
        .install_step(subject, InstallStep::FindPatchFiles)?;

    log::debug!("Normalizing paths...");
    if let Err(e) = r#mod.normalize_paths().await {
        log::error!("Path normalization failed: {}", e);
    }

    r#mod.resolve_sources().await;

    mods.push(r#mod.clone());
    log::info!("Mod successfully added.");
    Ok((r#mod, warning))
}

#[tauri::command]
pub async fn add_mod_folder(state: State<'_, AppState>, folder: PathBuf) -> TAResult<InstalledMod> {
    let _data_op = state.data_op().into_ta_result()?;
    let mut mods = state.mods.lock().await;
    if mods.is_none() {
        return anyhow::anyhow!("mods not read").into_ta_result();
    }
    let mods = mods.as_mut().unwrap();

    let (r#mod, warning) = install_from_folder(&state.base_path, mods, &folder).await?;
    Ok(InstalledMod { r#mod, warning })
}

/// Install any mix of archive files and plain folders in one go, dispatching
/// each path to the right installer. Each path locks the mods mutex
/// independently, so one item's failure never blocks the rest and nothing
/// ever nests a lock inside another lock.
#[tauri::command]
pub async fn add_paths(state: State<'_, AppState>, paths: Vec<PathBuf>) -> TAResult<Vec<TAResult<InstalledMod>>> {
    let _data_op = state.data_op().into_ta_result()?;
    log::info!("Adding mods from {} path(s)...", paths.len());

    let mut results = Vec::with_capacity(paths.len());
    for path in paths {
        let is_dir = tokio::fs::metadata(&path)
            .await
            .map(|m| m.is_dir())
            .unwrap_or(false);

        let result = if is_dir {
            let mut mods = state.mods.lock().await;
            match mods.as_mut() {
                Some(mods) => install_from_folder(&state.base_path, mods, &path).await,
                None => anyhow::anyhow!("mods not read").into_ta_result(),
            }
        } else {
            let mut mods = state.mods.lock().await;
            match mods.as_mut() {
                Some(mods) => install_from_archive(&state, mods, &path).await,
                None => anyhow::anyhow!("mods not read").into_ta_result(),
            }
        };

        results.push(result.map(|(r#mod, warning)| InstalledMod { r#mod, warning }));
    }

    Ok(results)
}

/// Install a mod by downloading an archive from a direct `https://` URL
/// first (into a throwaway temp directory), then running it through the
/// same install path as a locally picked archive file. Records where the
/// mod came from in a `.hd2mm-origin.json` sidecar next to the mod, without
/// ever touching the author's own `manifest.json`.
#[tauri::command]
pub async fn add_mod_from_url(state: State<'_, AppState>, url: String) -> TAResult<InstalledMod> {
    let _data_op = state.data_op().into_ta_result()?;
    log::info!("Downloading mod from {}...", download::redact_url(&url));

    let staging_root = state.base_path.join(download::STAGING_DIRECTORY);
    let downloaded = match download::download_archive(&url, &staging_root).await {
        Ok(d) => d,
        Err(e) => {
            let subject = download::redact_url(&url);
            let mut err = InstallError::new(subject, InstallStep::Download, e);
            if format!("{err}").contains("not a supported archive") {
                err = err.with_hint(
                    "The link doesn't lead straight to the file. Download the mod from its page in your browser, \
                     then add the downloaded file with Add.",
                );
            }
            return Err(report(err));
        }
    };

    let install_result = {
        let mut mods = state.mods.lock().await;
        match mods.as_mut() {
            Some(mods) => install_from_archive(&state, mods, &downloaded.path).await,
            None => anyhow::anyhow!("mods not read").into_ta_result(),
        }
    };

    // The staged download (and its throwaway parent directory) is no longer
    // needed either way -- the archive contents were copied out on success.
    let _ = tokio::fs::remove_dir_all(&downloaded.temp_dir).await;

    let (mut r#mod, warning) = install_result?;

    log::info!("Recording install origin...");
    let mut origin_source = sources::source_from_page_url(&url).unwrap_or_else(|| Source {
        provider: sources::provider_from_url(&url),
        id: None,
        url: Some(url.clone()),
        version: None,
    });
    // A GitHub release-asset link names its release: record that as the
    // installed version, so update checks work for this mod right away.
    let mut installed_files = Vec::new();
    if let Some(tag) = sources::github_tag_from_download_url(&url) {
        origin_source.version = Some(tag);
        installed_files.push(sources::InstalledFile {
            provider: "github".to_string(),
            file_name: url.rsplit('/').next().map(|n| {
                percent_encoding::percent_decode_str(n.split(['?', '#']).next().unwrap_or(n))
                    .decode_utf8_lossy()
                    .into_owned()
            }),
            ..Default::default()
        });
    }
    if let Err(e) =
        sources::write_origin_sidecar_with_files(&r#mod.directory, vec![origin_source], installed_files).await
    {
        log::error!("Failed to write origin sidecar: {}", e);
    }

    r#mod.resolve_sources().await;

    {
        let mut mods = state.mods.lock().await;
        if let Some(mods) = mods.as_mut() {
            if let Some(existing) = mods.iter_mut().find(|m| m.guid() == r#mod.guid()) {
                *existing = r#mod.clone();
            }
        }
    }

    Ok(InstalledMod { r#mod, warning })
}
/// Install `archive_path` as an update of the existing mod `existing_guid`,
/// used by both the browser handoff and the "Update from {site}" flow.
///
/// The new content is fully staged (extracted, manifest resolved, patch
/// layout detected) in a throwaway directory under the mods folder before
/// anything about the existing mod is touched. Only once that succeeds is
/// the old mod directory swapped out for the new one; on any failure before
/// the swap the old mod is left completely untouched, and the staging
/// directory is always cleaned up.
///
/// GUID handling: if the newly-installed manifest is one this manager
/// generated itself (no manifest.json in the update), the *old* GUID is
/// kept so existing profile configs referencing this mod keep working. If
/// the update ships its own manifest with its own GUID, that GUID is kept
/// instead (even if it differs from the old one) and the change is logged
/// -- profile configs are not migrated in that case.
pub(crate) async fn install_update_from_archive(
    state: &AppState,
    mods: &mut Vec<Mod>,
    archive_path: &Path,
    existing_guid: Uuid,
) -> TAResult<(Mod, Option<String>)> {
    log::info!("Updating mod {{{}}} from {:?}...", existing_guid, archive_path);
    let subject = subject_of(archive_path);
    install_update_steps(state, mods, archive_path, existing_guid, &subject).await.map_err(report)
}

async fn install_update_steps(
    state: &AppState,
    mods: &mut Vec<Mod>,
    archive_path: &Path,
    existing_guid: Uuid,
    subject: &str,
) -> Result<(Mod, Option<String>), InstallError> {
    let replace = InstallStep::Replace;
    let old_mod = mods
        .iter()
        .find(|m| m.guid() == existing_guid)
        .cloned()
        .ok_or_else(|| anyhow::anyhow!("the mod to update (GUID {{{}}}) is no longer in the mod list", existing_guid))
        .install_step(subject, replace)?;
    let old_dir = old_mod.directory.clone();
    let mods_root = state.base_path.join(MODS_DIRECTORY);
    // The old folder is moved aside and replaced below: make sure it really
    // is one mod's folder in the storage before anything is created.
    mod_folder::ensure_mod_folder(&mods_root, &old_dir).install_step(subject, replace)?;

    let staging_dir = mods_root.join(format!("{}{}", mod_folder::UPDATE_STAGING_PREFIX, Uuid::new_v4()));
    tokio::fs::create_dir_all(&staging_dir).await.install_step(subject, InstallStep::PrepareFolder)?;
    let discard_staging = || async {
        if let Err(e) = mod_folder::remove_mod_folder(&mods_root, &staging_dir).await {
            log::error!("Couldn't remove the update's staging folder: {:#}", e);
        }
    };

    let staged = stage_update(&staging_dir, archive_path, subject).await;

    let (mut manifest, warning) = match staged {
        Ok(ok) => ok,
        Err(e) => {
            discard_staging().await;
            return Err(e);
        }
    };

    let final_guid = if is_local_generated(&manifest) {
        if let Manifest::Legacy(legacy) = &mut manifest {
            legacy.guid = existing_guid;
            // The generated manifest is named after the update's archive
            // file ("CoolMod-1.4.zip" -> "CoolMod-1"); it's the same mod, so
            // keep the name and description the user already knows it by.
            legacy.name = old_mod.name().to_string();
            legacy.description = match &old_mod.manifest {
                Manifest::Legacy(m) => m.description.clone(),
                Manifest::V1(m) => m.description.clone(),
                Manifest::V2(m) => m.description.clone(),
            };
        }
        existing_guid
    } else {
        let new_guid = match &manifest {
            Manifest::Legacy(m) => m.guid,
            Manifest::V1(m) => m.guid,
            Manifest::V2(m) => m.guid,
        };
        if new_guid != existing_guid {
            // Keeping a new ID that another installed mod already has would
            // leave two mods with one ID (and deleting one of them by ID
            // could then hit the other's files): refuse before touching
            // anything.
            if let Some(other) = mods.iter().find(|m| m.guid() == new_guid) {
                let err = InstallError::new(
                    subject,
                    replace,
                    anyhow::anyhow!(
                        "its manifest.json gives it the ID (GUID) {{{}}}, and \"{}\" in your mod list already has that ID",
                        new_guid,
                        other.name()
                    ),
                )
                .with_hint(format!(
                    "This file doesn't look like an update of \"{}\": it carries the ID of \"{}\", a different mod \
                     in your list, so nothing was changed. Check that it's the right file; if it is, let the mod's \
                     author know that it reuses another mod's ID.",
                    old_mod.name(),
                    other.name()
                ));
                discard_staging().await;
                return Err(err);
            }
            log::info!(
                "Update for mod {{{}}} ships its own GUID {{{}}}; keeping the new one (profile entries referencing the old GUID will no longer match).",
                existing_guid, new_guid
            );
        }
        new_guid
    };

    // Persist the (possibly GUID-rewritten) manifest into staging before the swap.
    let manifest_data = match serde_json::to_vec_pretty(&manifest) {
        Ok(d) => d,
        Err(e) => {
            discard_staging().await;
            return Err(InstallError::new(subject, replace, e));
        }
    };
    if let Err(e) = tokio::fs::write(staging_dir.join(MANIFEST_FILE), manifest_data).await {
        discard_staging().await;
        return Err(InstallError::new(subject, replace, e));
    }

    log::info!("Swapping in updated content for mod {{{}}}...", final_guid);
    let backup_dir = mods_root.join(format!("{}{}", mod_folder::UPDATE_BACKUP_PREFIX, Uuid::new_v4()));
    // Note where the old version belongs before setting it aside, so that
    // if DDMM is closed (or crashes) mid-swap, the next start can put it
    // back instead of guessing.
    let record = mod_folder::backup_record_path(&backup_dir);
    let record_data = serde_json::json!({ "folder": old_dir.file_name().map(|n| n.to_string_lossy().into_owned()) });
    if let Err(e) = tokio::fs::write(&record, record_data.to_string()).await {
        discard_staging().await;
        return Err(InstallError::new(subject, replace, e));
    }

    if let Err(e) = crate::fs_util::move_path(&old_dir, &backup_dir).await {
        discard_staging().await;
        let _ = tokio::fs::remove_file(&record).await;
        return Err(InstallError::new(subject, replace, e));
    }

    if let Err(e) = crate::fs_util::move_path(&staging_dir, &old_dir).await {
        // Roll back: put the old content back where it was.
        match crate::fs_util::move_path(&backup_dir, &old_dir).await {
            Ok(()) => {
                let _ = tokio::fs::remove_file(&record).await;
            }
            // The record stays, so the next start restores it.
            Err(rollback) => log::error!("Couldn't put {:?} back after a failed update: {:#}", old_dir, rollback),
        }
        discard_staging().await;
        return Err(InstallError::new(subject, replace, e));
    }

    match mod_folder::remove_mod_folder(&mods_root, &backup_dir).await {
        Ok(()) => {
            let _ = tokio::fs::remove_file(&record).await;
        }
        // E.g. a file in it still open on Windows: the record stays, and
        // the next start finishes the cleanup.
        Err(e) => log::warn!("Couldn't remove the previous version of the updated mod yet: {:#}", e),
    }

    let mut new_mod = Mod {
        manifest,
        directory: old_dir,
        sources: Vec::new(),
    };

    if let Err(e) = new_mod.normalize_paths().await {
        log::error!("Path normalization failed: {}", e);
    }
    new_mod.resolve_sources().await;

    mods.retain(|m| m.guid() != existing_guid);
    mods.push(new_mod.clone());

    log::info!("Mod {{{}}} updated successfully.", new_mod.guid());
    Ok((new_mod, warning))
}

/// Put DDMM's mod storage back in order after an update that didn't finish
/// (DDMM closed or crashed mid-swap, or a file still in use on Windows kept
/// the old version from being deleted). Runs once, before the mods are
/// first read. Never deletes a mod that isn't also installed elsewhere:
///
/// - `.update-backup-<id>` (the old version set aside during an update):
///   put back into its folder when that folder is missing, deleted when
///   the updated mod is in place, and otherwise restored under a free name;
/// - `.update-<id>` (an update's staging copy, never the only copy of
///   anything): deleted;
/// - any other dot-folder with a manifest.json (a mod installed by an
///   older version from a file whose name started with a dot): renamed to
///   a visible name so it keeps showing up.
///
/// Problems are logged, never fatal: the mod list still loads.
pub(crate) async fn recover_leftover_folders(mods_root: &Path) {
    let Ok(mut entries) = tokio::fs::read_dir(mods_root).await else { return };
    let mut backups = Vec::new();
    let mut staging = Vec::new();
    let mut hidden_mods = Vec::new();
    let mut records = Vec::new();
    while let Ok(Some(entry)) = entries.next_entry().await {
        let Some(name) = entry.file_name().to_str().map(str::to_string) else { continue };
        if !name.starts_with('.') {
            continue;
        }
        let path = entry.path();
        let is_dir = tokio::fs::symlink_metadata(&path).await.map(|m| m.is_dir()).unwrap_or(false);
        if let Some(rest) = name.strip_prefix(mod_folder::UPDATE_BACKUP_PREFIX) {
            if is_dir && Uuid::parse_str(rest).is_ok() {
                backups.push(path);
            } else if !is_dir
                && rest
                    .strip_suffix(mod_folder::UPDATE_BACKUP_RECORD_SUFFIX)
                    .is_some_and(|id| Uuid::parse_str(id).is_ok())
            {
                records.push(path);
            }
        } else if let Some(rest) = name.strip_prefix(mod_folder::UPDATE_STAGING_PREFIX) {
            if is_dir && Uuid::parse_str(rest).is_ok() {
                staging.push(path);
            }
        } else if is_dir && path.join(MANIFEST_FILE).is_file() {
            hidden_mods.push((path, name));
        }
    }

    for backup in backups {
        if let Err(e) = recover_update_backup(mods_root, &backup).await {
            log::error!("Couldn't recover {:?}, left as it is: {:#}", backup, e);
        }
    }
    for dir in staging {
        match mod_folder::remove_mod_folder(mods_root, &dir).await {
            Ok(()) => log::info!("Removed {:?}, left over from an update that didn't finish.", dir),
            Err(e) => log::warn!("Couldn't remove {:?}: {:#}", dir, e),
        }
    }
    for record in records {
        let backup = record.with_file_name(
            record
                .file_name()
                .unwrap_or_default()
                .to_string_lossy()
                .trim_end_matches(mod_folder::UPDATE_BACKUP_RECORD_SUFFIX),
        );
        if tokio::fs::symlink_metadata(&backup).await.is_err() && mod_folder::ensure_mod_folder(mods_root, &record).is_ok() {
            let _ = tokio::fs::remove_file(&record).await;
        }
    }
    for (dir, name) in hidden_mods {
        let target = mods_root.join(mod_folder::free_folder_name(mods_root, &name, &|_| false));
        match crate::fs_util::move_path(&dir, &target).await {
            Ok(()) => log::info!("Renamed the mod folder {:?} to {:?} so it stays visible.", dir, target),
            Err(e) => log::error!("Couldn't rename the mod folder {:?}: {:#}", dir, e),
        }
    }
}

/// One `.update-backup-<id>` folder; see [`recover_leftover_folders`].
async fn recover_update_backup(mods_root: &Path, backup: &Path) -> anyhow::Result<()> {
    mod_folder::ensure_mod_folder(mods_root, backup)?;
    let record = mod_folder::backup_record_path(backup);
    let recorded: Option<String> = match tokio::fs::read(&record).await {
        Ok(data) => serde_json::from_slice::<serde_json::Value>(&data)
            .ok()
            .and_then(|v| v.get("folder").and_then(|f| f.as_str()).map(str::to_string))
            .filter(|n| !n.is_empty() && !n.starts_with('.') && mod_folder::ensure_mod_folder(mods_root, &mods_root.join(n)).is_ok()),
        Err(_) => None,
    };
    let backup_manifest = read_manifest_quietly(&backup.join(MANIFEST_FILE)).await;

    let restore_to = |name: &str| mods_root.join(mod_folder::free_folder_name(mods_root, name, &|_| false));
    let done = |what: &str| log::info!("{what} {:?} (left over from an update that didn't finish).", backup);

    let target = if let Some(folder) = recorded {
        let original = mods_root.join(&folder);
        if tokio::fs::symlink_metadata(&original).await.is_err() {
            // Stopped between setting the old version aside and moving the
            // new one in: the old version is the only copy. Put it back.
            original
        } else if original.join(MANIFEST_FILE).is_file() {
            // The updated mod is in place: this is the old version.
            mod_folder::remove_mod_folder(mods_root, backup).await?;
            let _ = tokio::fs::remove_file(&record).await;
            done("Removed the previous version");
            return Ok(());
        } else {
            restore_to(&folder)
        }
    } else {
        // Left by an older DDMM, which didn't record the folder.
        let Some(manifest) = backup_manifest else {
            log::warn!("Leaving {:?} alone: it has no manifest.json to tell which mod it is.", backup);
            return Ok(());
        };
        if installed_guid_exists(mods_root, manifest_guid(&manifest)).await {
            mod_folder::remove_mod_folder(mods_root, backup).await?;
            done("Removed the previous version");
            return Ok(());
        }
        restore_to(manifest_name(&manifest))
    };

    mod_folder::ensure_mod_folder(mods_root, &target)?;
    crate::fs_util::move_path(backup, &target).await?;
    let _ = tokio::fs::remove_file(&record).await;
    log::info!("Restored {:?} to {:?} (left over from an update that didn't finish).", backup, target);
    Ok(())
}

async fn read_manifest_quietly(file: &Path) -> Option<Manifest> {
    let data = tokio::fs::read(file).await.ok()?;
    Manifest::parse(&data, &file.to_string_lossy()).ok()
}

fn manifest_guid(manifest: &Manifest) -> Uuid {
    match manifest {
        Manifest::Legacy(m) => m.guid,
        Manifest::V1(m) => m.guid,
        Manifest::V2(m) => m.guid,
    }
}

fn manifest_name(manifest: &Manifest) -> &str {
    match manifest {
        Manifest::Legacy(m) => &m.name,
        Manifest::V1(m) => &m.name,
        Manifest::V2(m) => &m.name,
    }
}

/// Whether a visible mod folder in `mods_root` has a manifest with `guid`.
async fn installed_guid_exists(mods_root: &Path, guid: Uuid) -> bool {
    let Ok(mut entries) = tokio::fs::read_dir(mods_root).await else { return false };
    while let Ok(Some(entry)) = entries.next_entry().await {
        if is_hidden_name(&entry.file_name()) {
            continue;
        }
        if let Some(m) = read_manifest_quietly(&entry.path().join(MANIFEST_FILE)).await {
            if manifest_guid(&m) == guid {
                return true;
            }
        }
    }
    false
}

/// Extract `archive_path` into `staging_dir` and resolve its manifest
/// (generating a local one, with patch-layout auto-detection, if it ships
/// none), without touching anything outside `staging_dir`.
async fn stage_update(
    staging_dir: &Path,
    archive_path: &Path,
    subject: &str,
) -> Result<(Manifest, Option<String>), InstallError> {
    let archive = Archive::open(archive_path).install_step(subject, InstallStep::OpenArchive)?;
    let manifest_file = staging_dir.join(MANIFEST_FILE);
    let name = archive_path
        .file_name()
        .and_then(|n| n.to_str())
        .map(|n| crate::mod_import::display_name_from_file(n, true))
        .unwrap_or_else(|| "update".to_string());

    let (archive, mut manifest) = resolve_manifest(archive, name, manifest_file)
        .await
        .map_err(|e| manifest_failure(subject, e))?;

    extract_archive(archive, staging_dir.to_path_buf()).await.install_step(subject, InstallStep::Extract)?;

    let warning = apply_patch_layout(staging_dir, &mut manifest)
        .await
        .install_step(subject, InstallStep::FindPatchFiles)?;

    Ok((manifest, warning))
}

