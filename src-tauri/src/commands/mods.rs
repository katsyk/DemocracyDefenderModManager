    /// A v1 mod archive whose options are folders named `options`, each
    /// with a patch file holding `content`.
    fn options_mod_zip(path: &Path, guid: &str, name: &str, options: &[&str], content: &[u8]) {
        let opts: Vec<serde_json::Value> = options
            .iter()
            .map(|o| serde_json::json!({ "Name": o, "Description": "", "Include": [o] }))
            .collect();
        let manifest = serde_json::json!({ "Version": 1, "Guid": guid, "Name": name, "Description": "", "Options": opts });
        let patch = patch_file_name();
        let mut entries = vec![("manifest.json".to_string(), manifest.to_string().into_bytes())];
        for o in options {
            entries.push((format!("{o}/{patch}"), content.to_vec()));
        }
        std::fs::write(path, zip_bytes(&as_entries(&entries))).unwrap();
    }

    /// profiles.json with `other` first, then the mod to replace (off, its
    /// second option off), and in a second profile on.
