pub(crate) const MODS_DIRECTORY: &'static str = "mods/";
pub(crate) const MANIFEST_FILE: &'static str = "manifest.json";
const NO_PATCH_FILES_WARNING: &str = "no Helldivers 2 patch files found in this archive";

/// The JSON shape returned by every install command: a [`Mod`] plus an
/// optional, non-fatal warning (currently only "no Helldivers 2 patch files
/// found").
///
/// When the file had the ID of an installed mod and the user was asked
/// (see [`crate::replace_prompt`]): `replaced` -- the mod is the installed
/// one, replaced in place by the file; `kept` -- the user kept the
/// installed mod, which is the mod returned, unchanged, and nothing was
/// installed.
#[derive(Debug, Clone, Serialize)]
#[serde(rename_all = "PascalCase")]
pub struct InstalledMod {
    #[serde(flatten)]
    pub r#mod: Mod,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub warning: Option<String>,
    #[serde(skip_serializing_if = "std::ops::Not::not")]
    pub replaced: bool,
    #[serde(skip_serializing_if = "std::ops::Not::not")]
    pub kept: bool,
}

impl InstalledMod {
    /// A newly added mod (or an updated one).
    pub fn added(r#mod: Mod, warning: Option<String>) -> Self {
        InstalledMod { r#mod, warning, replaced: false, kept: false }
    }

    fn kept(existing: Mod) -> Self {
        InstalledMod { r#mod: existing, warning: None, replaced: false, kept: true }
    }
}

/// A manifest counts as "generated by us" (as opposed to one an author
/// shipped) exactly when it's the `LOCAL`-prefixed legacy manifest
/// `generate_local_manifest` produces. Only those are safe to rewrite with
/// an auto-detected `Options` list -- an author's own manifest.json is
/// never touched.
fn is_local_generated(manifest: &Manifest) -> bool {
    matches!(manifest, Manifest::Legacy(m) if m.guid.as_bytes().get(..5) == Some(b"LOCAL"))
}

/// After extraction/copy, if (and only if) the manifest was generated by us
/// because the mod shipped no `manifest.json` of its own, look for where
/// the actual Helldivers 2 patch files ended up and, if they're not at the
/// mod root, fill in `Options` (persisting the rewritten manifest.json) so
/// deploy and the existing option picker find them without any further
/// user action. Returns a non-fatal warning if no patch files were found
/// anywhere.
async fn apply_patch_layout(mod_dir: &Path, manifest: &mut Manifest) -> anyhow::Result<Option<String>> {
    if !is_local_generated(manifest) {
        return Ok(None);
    }

    let layout = detect_patch_layout(mod_dir).await?;

    match layout {
        // Patch files at the top next to a wrapper folder with a
        // manifest.json: installed the way it always was, but say so (see
        // `crate::mod_root`).
        PatchLayout::RootHasFiles => Ok(crate::mod_root::wrapped_manifest_beside_patch_files(mod_dir).map(|folder| {
            format!(
                "This mod has Helldivers 2 patch files at its top and a manifest.json in its folder \"{folder}\", so it \
                 isn't clear which is the mod. DDMM installed it as before: the top-level patch files are the mod, \
                 and that manifest.json isn't used (the folder's files are kept, but not deployed). Ask the mod's \
                 author how it's meant to be installed."
            )
        })),
        PatchLayout::Options(paths) => {
            if let Manifest::Legacy(legacy) = manifest {
                legacy.options = Some(paths);
            }
            let manifest_file = mod_dir.join(MANIFEST_FILE);
            let data = serde_json::to_vec_pretty(manifest)?;
            tokio::fs::write(manifest_file, data).await?;
            Ok(None)
        }
        PatchLayout::NoneFound => {
            let nested = find_nested_archives(mod_dir).await;
            if nested.is_empty() {
                Ok(Some(NO_PATCH_FILES_WARNING.to_string()))
            } else {
                Ok(Some(format!(
                    "{NO_PATCH_FILES_WARNING}. It contains other archives ({}): it's probably a pack of several \
                     versions or parts. Extract the one you want with 7-Zip and add that to DDMM instead.",
                    nested.join(", ")
                )))
            }
        }
    }
}

/// Up to five archive files anywhere in `dir` (a few levels deep): a mod
/// that ships its variants as archives inside the archive. They are never
/// unpacked automatically (an archive inside an archive is also the
/// classic way to sneak past size and path checks); the warning names them
/// so the user knows what to do.
async fn find_nested_archives(dir: &Path) -> Vec<String> {
    let mut found = Vec::new();
    let mut stack = vec![(dir.to_path_buf(), 0usize)];
    while let Some((current, depth)) = stack.pop() {
        let Ok(mut entries) = tokio::fs::read_dir(&current).await else { continue };
        while let Ok(Some(entry)) = entries.next_entry().await {
            let Ok(file_type) = entry.file_type().await else { continue };
            let name = entry.file_name().to_string_lossy().into_owned();
            if file_type.is_dir() && depth < 4 {
                stack.push((entry.path(), depth + 1));
            } else if file_type.is_file()
                && crate::commands::handoff::ARCHIVE_SUFFIXES.iter().any(|s| name.to_ascii_lowercase().ends_with(s))
            {
                found.push(name);
            }
        }
    }
    found.sort_by(|a, b| crate::utils::natural_cmp(a, b));
    found.truncate(5);
    found
}

#[allow(dead_code)]
trait ZipResult<S, E, T> {
    fn zip(self, other: Result<T, E>) -> Result<(S, T), E>;
    fn zip_value(self, other: T) -> Result<(S, T), E>;
}

impl<S, E, T> ZipResult<S, E, T> for Result<S, E> {
    fn zip(self, other: Result<T, E>) -> Result<(S, T), E> {
        match (self, other) {
            (Ok(a), Ok(b)) => Ok((a, b)),
            (Err(e), Ok(_)) => Err(e),
            (Ok(_), Err(e)) => Err(e),
            (Err(e), Err(_)) => Err(e),
        }
    }

    fn zip_value(self, other: T) -> Result<(S, T), E> {
        match self {
            Ok(s) => Ok((s, other)),
            Err(e) => Err(e)
        }
    }
}

/// Resolve an image path from a mod's manifest (`IconPath`, an option's
/// `Image`) to the file on disk, with the same rules as deploy
/// ([`crate::utils::fix_path_casing`]: `\` separators, any casing, never
/// outside the mod folder). `None` when there's no such file, so the UI
/// shows its default icon. Only answers for folders inside `mods/`.
pub(crate) async fn resolve_mod_image_path(base_path: &Path, mod_directory: &Path, image: &str) -> Option<PathBuf> {
    let mods_root = tokio::fs::canonicalize(base_path.join(MODS_DIRECTORY)).await.ok()?;
    let mod_dir = tokio::fs::canonicalize(mod_directory).await.ok()?;
    if !mod_dir.starts_with(&mods_root) || mod_dir == mods_root {
        return None;
    }
    let relative = crate::utils::fix_path_casing(&mod_dir, Path::new(image)).await.ok()?;
    if relative.as_os_str().is_empty() {
        return None;
    }
    // Hand back the path as the app knows it (not the canonical form, which
    // is `\\?\C:\…` on Windows); the asset scope allows both.
    let file = mod_directory.join(relative);
    tokio::fs::metadata(&file).await.ok().filter(|m| m.is_file()).map(|_| file)
}

#[tauri::command]
pub async fn resolve_mod_image(
    state: State<'_, AppState>,
    mod_directory: PathBuf,
    image: String,
) -> TAResult<Option<PathBuf>> {
    Ok(resolve_mod_image_path(&state.base_path, &mod_directory, &image).await)
}

#[tauri::command]
pub async fn get_mods(state: State<'_, AppState>) -> TAResult<Vec<Mod>> {
    let mut state_mods = state.mods.lock().await;
    log::info!("Loading mods...");
    let mods = ensure_mods_loaded(&mut state_mods, &state).await?;
    Ok(mods.clone())
}

/// Read every installed mod from disk into `state_mods` the first time it's
/// needed (a no-op once loaded) and return it. Shared by `get_mods` and by
/// the browser bridge, which can receive an install before the frontend
/// has ever called `get_mods` -- e.g. a first run still on the Settings
/// page, or DDMM just launched by the native-messaging host.
///
/// `state_mods` is `state`'s mod list, locked by the caller. The first read
/// finishes what an update DDMM was closed in the middle of left undone
/// (see [`recover_leftover_folders`]): the ID changes it finished (or
/// couldn't write to profiles.json yet) are recorded as this session's
/// renames, so the page moves its entries too (`get_guid_renames`), and
/// `load_profiles` stops waiting for the mod list.
pub(crate) async fn ensure_mods_loaded<'a>(
    state_mods: &'a mut Option<Vec<Mod>>,
    state: &AppState,
) -> TAResult<&'a mut Vec<Mod>> {
    let mut renames = Vec::new();
    let mut notices = Notices::default();
    let loaded = ensure_mods_loaded_into(state_mods, &state.base_path, &mut renames, &mut notices).await;
    // Kept even when reading the list failed after the recovery: what it
    // did stands. A later read recovers again and finds the same, which
    // isn't recorded (or shown) twice.
    let known = state.guid_renames();
    for (old, new) in renames {
        if !known.contains(&(old, new)) {
            state.record_guid_rename(old, new);
        }
    }
    state.add_startup_notices(notices);
    let mods = loaded?;
    state.mods_recovered.store(true, std::sync::atomic::Ordering::Release);
    Ok(mods)
}

/// [`ensure_mods_loaded`] for the mod storage of `base_path`, without an
/// [`AppState`]; also returns the ID changes the first read's recovery
/// found and what the user should be told about it (see
/// [`crate::startup_notices`]) -- neither once loaded.
#[cfg(test)]
pub(crate) async fn ensure_mods_loaded_at<'a>(
    state_mods: &'a mut Option<Vec<Mod>>,
    base_path: &Path,
) -> TAResult<(&'a mut Vec<Mod>, Vec<(Uuid, Uuid)>, Notices)> {
    let mut renames = Vec::new();
    let mut notices = Notices::default();
    let mods = ensure_mods_loaded_into(state_mods, base_path, &mut renames, &mut notices).await?;
    Ok((mods, renames, notices))
}

/// [`ensure_mods_loaded_at`], with what the recovery found put in
/// `renames` and `notices` -- also when reading the list then fails.
async fn ensure_mods_loaded_into<'a>(
    state_mods: &'a mut Option<Vec<Mod>>,
    base_path: &Path,
    renames: &mut Vec<(Uuid, Uuid)>,
    notices: &mut Notices,
) -> TAResult<&'a mut Vec<Mod>> {
    if state_mods.is_some() {
        log::debug!("Mods already loaded.");
        return Ok(state_mods.as_mut().unwrap());
    }

    let mods_dir = base_path.join(MODS_DIRECTORY);
    let mut mods = Vec::new();
    if !mods_dir.is_dir() {
        // First run: nothing installed yet. Still record the (empty) list
        // as loaded, or every install command would fail with "mods not
        // read" until something called get_mods a second time.
        tokio::fs::create_dir_all(&mods_dir).await.into_ta_result()?;
    } else {
        let recovered = recover_leftover_folders(&mods_dir).await;
        let still_hidden = recovered.still_hidden;
        *renames = recovered.renames;
        *notices = recovered.notices;

        if fail_point(FailPoint::ModRead) {
            return Err(anyhow::anyhow!("simulated failure reading the mod list")).into_ta_result();
        }
        let mut mods_dir = tokio::fs::read_dir(mods_dir).await.into_ta_result()?;
        while let Some(entry) = mods_dir.next_entry().await.into_ta_result()? {
            let mod_dir = entry.path();

            // Folders starting with a dot are DDMM's own working folders
            // (an update's staging copy or the old version set aside
            // during one), never mods: loading one would list a mod twice.
            if is_hidden_name(&entry.file_name()) && !still_hidden.contains(&mod_dir) {
                log::debug!("Skipping working folder {:?}.", mod_dir);
                continue;
            }

            let manifest_file = mod_dir.join(MANIFEST_FILE);
            if !manifest_file.is_file() {
                continue;
            }

            // One unreadable manifest must not take the whole library down
            // with it (every later install would then fail with "mods not
            // read"): log it with the reason and skip that mod.
            let manifest = match tokio::fs::read(&manifest_file).await {
                Ok(data) => Manifest::parse(&data, &manifest_file.to_string_lossy()),
                Err(e) => Err(anyhow::anyhow!("can't read {:?}: {}", manifest_file, e)),
            };
            let manifest = match manifest {
                Ok(m) => m,
                Err(e) => {
                    log::error!("Skipping mod in {:?}: {:#}", mod_dir, e);
                    // One notice per folder: an update waiting on this
                    // manifest already said so.
                    if !notices.names_folder(&mod_dir) {
                        notices.push(StartupNotice::new(NoticeKind::ModUnreadable).named(folder_name(&mod_dir)).folder(&mod_dir));
                    }
                    continue;
                }
            };

            let mut r#mod = Mod {
                manifest,
                directory: mod_dir,
                sources: Vec::new(),
            };
            if let Err(e) = r#mod.normalize_paths().await {
                log::error!("Path normalization failed for {:?}: {:#}", r#mod.directory, e);
            }
            r#mod.resolve_sources().await;

            mods.push(r#mod);
        }
    }

    log::info!("Mods loaded.");
    Ok(state_mods.insert(mods))
}

/// `dir`'s own name, for a notice when there's no manifest to name it.
fn folder_name(dir: &Path) -> String {
    dir.file_name().map(|n| n.to_string_lossy().into_owned()).unwrap_or_default()
}

/// Delete the mod with `guid`: its folder, the versions its updates
/// replaced, its entries in every profile (profiles.json on disk too, so it
/// can't come back as "Mod not found"), and what the last update check said
/// about it.
///
/// Either the mod is removed completely, or nothing changes and the error
/// (in the "Couldn't remove ..." shape) says why -- see
/// [`delete_installed_mod`]. Returns as soon as the mod is out of the list
/// and the profiles, so the page can drop it right away; deleting its
/// files goes on in the background (and, for files still in use, finishes
/// on the next start).
#[tauri::command]
pub async fn delete_mod(state: State<'_, AppState>, guid: Uuid) -> TAResult<()> {
    let cleanup = delete_mod_with(&state, guid).await.into_ta_result()?;
    tauri::async_runtime::spawn(async move {
        if let Err(e) = cleanup.run().await {
            log::warn!("Some files of a deleted mod couldn't be deleted yet; the next start deletes them: {:#}", e);
        }
    });
    Ok(())
}

/// [`delete_mod`] without Tauri's `State` wrapper; the returned cleanup
/// deletes the files.
pub(crate) async fn delete_mod_with(state: &AppState, guid: Uuid) -> anyhow::Result<PendingCleanup> {
    let data_op = state.data_op()?;
    let mut mods = state.mods.lock().await;
    let Some(mods) = mods.as_mut() else {
        anyhow::bail!("mods not read");
    };

    log::info!("Deleting mod \"{}\"...", guid);
    let mut cleanup = delete_installed_mod(&state.base_path, mods, guid).await?;
    cleanup.data_op = Some(data_op);

    // An update found for the deleted mod must not show up on a new
    // install of it (which may come from another site).
    if let Some(report) = state.last_update_report.lock().await.as_mut() {
        report.results.retain(|e| e.guid != guid);
    }
    log::info!("Mod removed; deleting its files.");
    Ok(cleanup)
}

/// What's left to delete of a removed mod: its set-aside folder and the
/// versions its updates replaced. Everything in it is already hidden and
/// recorded so that it's never loaded or restored, whether or not this
/// finishes.
#[derive(Debug)]
pub(crate) struct PendingCleanup {
    mods_root: PathBuf,
    set_aside: Option<PathBuf>,
    backups: Vec<PathBuf>,
    /// Keeps a data folder move from starting while files are deleted.
    data_op: Option<tokio::sync::OwnedRwLockReadGuard<()>>,
}

impl PendingCleanup {
    /// Delete it all. An error means something is left for the next start.
    pub(crate) async fn run(self) -> anyhow::Result<()> {
        for backup in &self.backups {
            match mod_folder::remove_mod_folder(&self.mods_root, backup).await {
                Ok(()) => {
                    let _ = tokio::fs::remove_file(mod_folder::backup_record_path(backup)).await;
                }
                Err(e) => log::warn!("Couldn't remove {:?} yet: {:#}", backup, e),
            }
        }
        if let Some(set_aside) = &self.set_aside {
            finish_pending_delete(&self.mods_root, set_aside).await?;
        }
        log::info!("Mod deletion complete.");
        Ok(())
    }
}

/// The work of [`delete_mod`], on the already-locked mod list.
///
/// 1. The mod's folder must pass [`mod_folder::ensure_mod_folder`].
/// 2. The whole folder is renamed to a hidden `.delete-<id>` folder (with a
///    record next to it saying DDMM set it aside). A rename either works or
///    changes nothing, so a file in use (Windows) can't leave the mod half
///    deleted: it stays installed and listed, and the error says so.
/// 3. Only then does the mod leave the list and the saved profiles, and
///    the versions its updates set aside are marked so they're never put
///    back (see [`claim_replaced_versions_of`]).
/// 4. The returned [`PendingCleanup`] deletes the set-aside folder
///    (read-only files included) and those versions. What it can't delete
///    (a file still in use) stays hidden -- never loaded, never in the way
///    of adding the mod again -- and the next start finishes it.
///
/// A mod whose folder is already gone (deleted by hand while DDMM was
/// open) is simply removed.
pub(crate) async fn delete_installed_mod(base_path: &Path, mods: &mut Vec<Mod>, guid: Uuid) -> anyhow::Result<PendingCleanup> {
    use crate::install_error::{RemoveError, RemoveStep};
    let Some(i) = mods.iter().position(|m| m.guid() == guid) else {
        anyhow::bail!("mod with GUID {{{}}} not found", guid);
    };
    let mods_root = base_path.join(MODS_DIRECTORY);
    let name = mods[i].name().to_string();
    let dir = mods[i].directory.clone();

    // Checked before the mod leaves the list, so a refused delete doesn't
    // leave a mod that silently comes back on the next launch.
    mod_folder::ensure_mod_folder(&mods_root, &dir).map_err(|e| RemoveError::new(&name, RemoveStep::CheckFolder, e))?;
    let set_aside = take_out_mod_folder(&mods_root, &dir)
        .await
        .map_err(|e| RemoveError::new(&name, RemoveStep::TakeOut, e))?;

    mods.remove(i);
    log::info!("Mod removed from the mod list.");
    match crate::commands::profiles::remove_from_saved_profiles(base_path, guid).await {
        Ok(0) => {}
        Ok(n) => log::info!("Removed {n} profile entr(ies) of the deleted mod."),
        Err(e) => log::warn!("Couldn't remove the deleted mod from profiles.json: {:#}", e),
    }
    let backups = claim_replaced_versions_of(&mods_root, &dir, guid, mods).await;
    Ok(PendingCleanup { mods_root, set_aside, backups, data_op: None })
}

/// Rename the mod folder `dir` to a new `.delete-<id>` folder in
/// `mods_root`, after writing the record that marks it as set aside by
/// DDMM. Returns the new folder, or `None` if `dir` is already gone. On
/// failure nothing is left changed. A rename that fails is tried again a
/// few times, a moment apart (a virus scanner or the search indexer often
/// has a new file open briefly).
async fn take_out_mod_folder(mods_root: &Path, dir: &Path) -> anyhow::Result<Option<PathBuf>> {
    match tokio::fs::symlink_metadata(dir).await {
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => {
            log::info!("{:?} is already gone.", dir);
            return Ok(None);
        }
        _ => {}
    }
    let set_aside = mods_root.join(format!("{}{}", mod_folder::PENDING_DELETE_PREFIX, Uuid::new_v4()));
    mod_folder::ensure_mod_folder(mods_root, &set_aside)?;
    let record = mod_folder::pending_delete_record_path(&set_aside);
    let data = serde_json::json!({ "folder": dir.file_name().map(|n| n.to_string_lossy().into_owned()) });
    tokio::fs::write(&record, data.to_string())
        .await
        .with_context(|| format!("couldn't write {:?}", record))?;

    let mut attempt = tokio::fs::rename(dir, &set_aside).await;
    for delay in mod_folder::REMOVE_RETRY_DELAYS {
        if attempt.is_ok() {
            break;
        }
        tokio::time::sleep(*delay).await;
        attempt = tokio::fs::rename(dir, &set_aside).await;
    }
    if let Err(e) = attempt {
        let _ = tokio::fs::remove_file(&record).await;
        return Err(anyhow::Error::from(e).context(format!("couldn't move {:?} to {:?}", dir, set_aside)));
    }
    Ok(Some(set_aside))
}

/// Delete a folder [`take_out_mod_folder`] set aside, then its record.
async fn finish_pending_delete(mods_root: &Path, set_aside: &Path) -> anyhow::Result<()> {
    mod_folder::remove_mod_folder(mods_root, set_aside).await?;
    let _ = tokio::fs::remove_file(mod_folder::pending_delete_record_path(set_aside)).await;
    Ok(())
}

#[tauri::command]
pub async fn add_mod(app: AppHandle, state: State<'_, AppState>, archive_file: PathBuf) -> TAResult<InstalledMod> {
    let _data_op = state.data_op().into_ta_result()?;
    add_archive(&state, &archive_file, &Asker::in_app(&app)).await
}

/// Answer a `install://replace-request` (see [`crate::replace_prompt`]):
/// the Mods page calls this with the user's Replace (`true`) or Cancel.
#[tauri::command]
pub async fn resolve_replace_request(state: State<'_, AppState>, request_id: String, replace: bool) -> TAResult<()> {
    if !state.replace_pending.lock().await.answer(&request_id, replace) {
        log::warn!("A replace question was answered after DDMM stopped waiting for it; nothing was changed.");
    }
    Ok(())
}

/// Add one archive the way Add, drag and drop and Add URL do: when its
/// manifest.json has the ID of an installed mod, `asker` is asked whether
/// to replace that mod (see [`decide_replace`]); otherwise, or when the
/// question can't be asked, it's an ordinary [`install_from_archive`].
///
/// Locks the mod list itself (never while the question is shown), so the
/// caller must not hold it.
pub(crate) async fn add_archive(state: &AppState, archive_file: &Path, asker: &Asker<'_>) -> TAResult<InstalledMod> {
    let replace = match decide_replace(state, archive_file, asker).await.into_ta_result()? {
        ReplaceChoice::Keep(existing) => return Ok(InstalledMod::kept(existing)),
        ReplaceChoice::Replace(target) => Some(target),
        ReplaceChoice::Install => None,
    };
    let mut mods = state.mods.lock().await;
    let Some(mods) = mods.as_mut() else {
        return anyhow::anyhow!("mods not read").into_ta_result();
    };
    let (r#mod, warning, replaced) = install_or_replace(state, mods, archive_file, replace).await?;
    Ok(InstalledMod { r#mod, warning, replaced, kept: false })
}

/// What to do with an archive about to be added, decided by
/// [`decide_replace`].
#[derive(Debug)]
pub(crate) enum ReplaceChoice {
    /// Add it (no installed mod has its ID, or nobody could be asked).
    Install,
    /// Replace the installed mod the user was asked about by it.
    Replace(ReplaceTarget),
    /// Keep the installed mod (returned as it is); add nothing.
    Keep(Mod),
}

/// The installed mod the user agreed to replace: its ID and its folder
/// (so that a different mod that has the ID by the time it's installed is
/// never replaced instead).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ReplaceTarget {
    pub guid: Uuid,
    pub directory: PathBuf,
}

/// If the archive's own manifest.json has the ID of an installed mod, ask
/// `asker` whether to replace that mod with it. The archive is read and
/// the question shown without holding the mod list; whatever changes
/// meanwhile, [`install_or_replace`] checks again before touching anything.
pub(crate) async fn decide_replace(state: &AppState, archive_file: &Path, asker: &Asker<'_>) -> anyhow::Result<ReplaceChoice> {
    if !asker.asks() {
        return Ok(ReplaceChoice::Install);
    }
    let path = archive_file.to_path_buf();
    let manifest = tokio::task::spawn_blocking(move || peek_archive_manifest(&path)).await.ok().flatten();
    let Some(manifest) = manifest else { return Ok(ReplaceChoice::Install) };
    let (offer, existing) = {
        let mut guard = state.mods.lock().await;
        let mods = ensure_mods_loaded(&mut guard, state).await.map_err(|e| e.0)?;
        match replace_offer(mods, &manifest, archive_file) {
            Some(found) => found,
            None => return Ok(ReplaceChoice::Install),
        }
    };
    Ok(match asker.ask(&offer).await {
        Some(true) => ReplaceChoice::Replace(ReplaceTarget { guid: offer.guid, directory: existing.directory }),
        Some(false) => ReplaceChoice::Keep(existing),
        None => ReplaceChoice::Install,
    })
}

/// The manifest.json an install of `archive_file` would use, if it has one
/// of its own (the same one [`resolve_manifest`] picks); `None` for an
/// archive without one, or one that can't be read.
fn peek_archive_manifest(archive_file: &Path) -> Option<Manifest> {
    let mut archive = Archive::open(archive_file).ok()?;
    let (_, entry) = crate::mod_root::find_archive_manifest(&mut archive).ok()??;
    let data = archive.read_path(&entry).ok()?;
    Manifest::parse(&data, &entry.to_string_lossy()).ok()
}

/// The question to ask when `manifest` (read from `archive_file`) has the
/// ID of a mod in `mods`, and that mod.
fn replace_offer(mods: &[Mod], manifest: &Manifest, archive_file: &Path) -> Option<(ReplaceOffer, Mod)> {
    let guid = manifest_guid(manifest);
    let existing = mods.iter().find(|m| m.guid() == guid)?;
    let file_name = subject_of(archive_file);
    let new_name = manifest_name(manifest).to_string();
    let new_version = crate::mod_import::nexus_ref_from_name(&file_name, true)
        .and_then(|n| n.version)
        .or_else(|| match manifest {
            Manifest::V1(m) => m.nexus_data.as_ref().map(|n| n.version.clone()),
            _ => None,
        });
    let installed_version = existing.sources.iter().find_map(|s| s.version.clone());
    let offer = ReplaceOffer {
        guid,
        file_name,
        installed_name: existing.name().to_string(),
        installed_version,
        same_name: existing.name().trim().eq_ignore_ascii_case(new_name.trim()),
        new_name,
        new_version,
    };
    Some((offer, existing.clone()))
}

/// Install `archive_file`: in place of the installed mod `replace` when
/// that's given and still installed (see [`replace_from_archive`]), else as
/// a new mod ([`install_from_archive`], which refuses a file whose ID is
/// installed). The `bool` says whether it replaced. A mod in another folder
/// that has the ID by now (the one asked about was removed and another
/// added meanwhile) is never replaced: that's refused.
pub(crate) async fn install_or_replace(
    state: &AppState,
    mods: &mut Vec<Mod>,
    archive_file: &Path,
    replace: Option<ReplaceTarget>,
) -> TAResult<(Mod, Option<String>, bool)> {
    if let Some(target) = replace {
        match mods.iter().find(|m| m.guid() == target.guid) {
            Some(m) if m.directory == target.directory => {
                let (r#mod, warning) = replace_from_archive(state, mods, archive_file, target.guid).await?;
                return Ok((r#mod, warning, true));
            }
            Some(m) => {
                return Err(report(
                    InstallError::new(
                        subject_of(archive_file),
                        InstallStep::Replace,
                        anyhow::anyhow!(
                            "\"{}\" in your mod list has its ID now, not the mod you chose to replace (it was \
                             removed meanwhile)",
                            m.name()
                        ),
                    )
                    .with_hint("Nothing was changed. Add the file again to be asked about the mod that has its ID now."),
                ));
            }
            None => log::info!(
                "The mod to replace ({{{}}}) is no longer installed; adding the file as a new mod.",
                target.guid
            ),
        }
    }
    let (r#mod, warning) = install_from_archive(state, mods, archive_file).await?;
    Ok((r#mod, warning, false))
}

/// Replace the installed mod `guid` by `archive_file`, whose manifest.json
/// has the same ID -- the user said so (see [`crate::replace_prompt`]).
///
/// The same in-place swap as an update ([`install_update_steps`]): the
/// file is staged and checked completely before the installed mod is
/// touched, then swapped in (crash safe); a failure, or a file that turns
/// out not to have that ID after all, leaves the installed mod as it was.
/// The mod keeps its ID and folder, so its place in every profile, on/off,
/// and option choices that still fit the new manifest.json (the rest are
/// reset, in profiles.json too; see `profiles::fit_saved_profiles`).
///
/// Where the mod came from is recorded afresh for the new file, as for a
/// new install of it: from its Nexus Mods download name (no API call, and
/// moved in with the new files), or by the caller that knows (Add URL, a
/// browser install). What the last update check said about the replaced
/// mod is dropped.
pub(crate) async fn replace_from_archive(
    state: &AppState,
    mods: &mut Vec<Mod>,
    archive_file: &Path,
    guid: Uuid,
) -> TAResult<(Mod, Option<String>)> {
    log::info!("Replacing mod {{{}}} with {:?}...", guid, archive_file);
    let subject = subject_of(archive_file);
    let (r#mod, warning) = install_update_steps(state, mods, archive_file, guid, &subject, true)
        .await
        .map_err(report)?;

    if let Some(report) = state.last_update_report.lock().await.as_mut() {
        report.results.retain(|e| e.guid != guid);
    }
    log::info!("Mod {{{}}} replaced.", guid);
    Ok((r#mod, warning))
}

/// Shared core of `add_mod`: prepares the mod directory, resolves the
/// manifest (from the archive if present, generating a local one
/// otherwise), extracts, and registers the mod.
///
/// Takes the already-locked mods vector rather than `State` directly so it
/// can be called both from a `#[tauri::command]` that holds the lock for a
/// single install, and from callers (like `add_paths`) that lock once per
/// item without ever calling back into another `#[tauri::command]` while
/// holding the mutex.
///
/// The mod's folder is named after the archive (made safe and unique, see
/// [`prepare_mod_dir`]); a generated manifest (the
/// archive ships none) gets a readable name from the file name instead,
/// without Nexus Mods' download suffix (see
/// [`crate::mod_import::display_name_from_file`]), and a Nexus download's
/// page and version are recorded (see [`record_nexus_from_file_name`]).
pub(crate) async fn install_from_archive(state: &AppState, mods: &mut Vec<Mod>, archive_file: &Path) -> TAResult<(Mod, Option<String>)> {
    log::debug!("Obtaining name...");
    let dir_name = archive_file
        .file_stem()
        .ok_or(anyhow::anyhow!("archive path has no file name"))?
        .to_str()
        .map(str::to_string)
        .ok_or(anyhow::anyhow!("file name conversion failed"))?;
    let file_name = archive_file.file_name().and_then(|n| n.to_str()).unwrap_or(&dir_name).to_string();
    let display_name = crate::mod_import::display_name_from_file(&file_name, true);

    log::info!("Adding mod from {:?}...", archive_file);
    let subject = subject_of(archive_file);
    let (mut r#mod, warning) =
        install_archive_steps(&state.base_path, mods, archive_file, &dir_name, &display_name, &subject, AddRoute::Archive)
            .await
            .map_err(report)?;
    record_nexus_from_file_name(mods, &mut r#mod, &file_name, true).await;
    Ok((r#mod, warning))
}

/// A mod just installed from a file Nexus Mods named (`Name-1234-1-0-...`)
/// gets that Nexus page, version and file recorded in its origin sidecar,
/// the same way import records them, so "Check for updates" works for it.
/// Read off the file name only: no Nexus API call.
///
/// Skipped when the mod already has an origin sidecar, or when its own
/// manifest names a different Nexus page. Callers that know where the file
/// came from (Add from URL, browser installs) write their origin afterwards,
/// which replaces this one: a download URL's attribution always wins.
async fn record_nexus_from_file_name(mods: &mut [Mod], r#mod: &mut Mod, file_name: &str, is_archive: bool) {
    let Some(sidecar) = nexus_sidecar_from_file_name(r#mod, file_name, is_archive).await else { return };
    if let Err(e) = sources::save_origin_sidecar(&r#mod.directory, &sidecar).await {
        log::error!("Failed to record the Nexus Mods source: {}", e);
        return;
    }
    r#mod.resolve_sources().await;
    if let Some(existing) = mods.iter_mut().find(|m| m.guid() == r#mod.guid()) {
        *existing = r#mod.clone();
    }
}

/// The origin record [`record_nexus_from_file_name`] writes for `r#mod`
/// (its sources resolved, its folder the one the record goes into), or
/// `None` when it writes none.
async fn nexus_sidecar_from_file_name(r#mod: &Mod, file_name: &str, is_archive: bool) -> Option<sources::OriginSidecar> {
    let nexus = crate::mod_import::nexus_ref_from_name(file_name, is_archive)?;
    let other_page = r#mod.sources.iter().any(|s| {
        s.provider.eq_ignore_ascii_case("nexus")
            && s.origin == sources::SourceOrigin::Manifest
            && sources::resolved_source_id(s).is_some_and(|id| id != nexus.mod_id)
    });
    if other_page || sources::load_origin_sidecar(&r#mod.directory).await.is_some() {
        return None;
    }
    let mut sidecar = sources::OriginSidecar {
        sources: Vec::new(),
        installed_at: std::time::SystemTime::now().duration_since(std::time::UNIX_EPOCH).map(|d| d.as_secs()).unwrap_or(0),
        installed_files: Vec::new(),
        skipped_versions: Vec::new(),
        imported_archive: None,
    };
    crate::mod_import::add_nexus_to_sidecar(&mut sidecar, &nexus, r#mod);
    (!sidecar.sources.is_empty() || !sidecar.installed_files.is_empty()).then_some(sidecar)
}

/// [`install_from_archive`] named `name` (the generated manifest's name
/// when the archive ships none, and -- made safe and unique by
/// [`prepare_mod_dir`] -- its folder's name) instead of after the archive
/// -- used by the bulk import, which picks a readable, unique name itself.
pub(crate) async fn install_from_archive_as(
    base_path: &Path,
    mods: &mut Vec<Mod>,
    archive_file: &Path,
    name: &str,
) -> TAResult<(Mod, Option<String>)> {
    log::info!("Adding mod from {:?}...", archive_file);
    let subject = subject_of(archive_file);
    install_archive_steps(base_path, mods, archive_file, name, name, &subject, AddRoute::Import).await.map_err(report)
}

/// Log a failed install (the whole message: which mod, which step, why)
/// and hand it to the frontend unchanged.
fn report(e: InstallError) -> anyhow_tauri::TACommandError {
    log::error!("{e}");
    anyhow_tauri::TACommandError(anyhow::Error::new(e))
}

async fn install_archive_steps(
    base_path: &Path,
    mods: &mut Vec<Mod>,
    archive_file: &Path,
    dir_name: &str,
    manifest_name: &str,
    subject: &str,
    route: AddRoute,
) -> Result<(Mod, Option<String>), InstallError> {
    log::debug!("Opening archive...");
    let mut archive = Archive::open(archive_file).install_step(subject, InstallStep::OpenArchive)?;

    log::info!("Preparing mod directory...");
    let mods_root = base_path.join(MODS_DIRECTORY);
    // An unreadable archive counts as "has one": resolving the manifest
    // below then reports the real problem.
    let has_manifest = archive_has_manifest(&mut archive);
    if !has_manifest {
        refuse_if_listed(mods, &mods_root, dir_name, subject)?;
    }
    let (mod_dir, folder_name) = prepare_mod_dir(archive_file, &mods_root, dir_name, subject).await?;
    let manifest_name = display_name(manifest_name, &folder_name);
    let manifest_file = mod_dir.join(MANIFEST_FILE);

    // From here on `mod_dir` is ours (prepare_mod_dir just created it), so
    // a failure must remove it again: a half-written directory with a
    // manifest.json would otherwise show up as an empty "ghost" mod on the
    // next launch and block retrying the same file with "mod directory
    // already exists" (e.g. after an archive was rejected as unsafe).
    let prepared: Result<(Mod, Option<String>), InstallError> = async {
        log::info!("Resolving manifest...");
        let (archive, manifest, root) = resolve_manifest(archive, manifest_name.to_string(), manifest_file.clone())
            .await
            .map_err(|e| manifest_failure(subject, e))?;

        let mut r#mod = Mod {
            manifest,
            directory: mod_dir.clone(),
            sources: Vec::new(),
        };

        log::info!("Checking for duplicate...");
        check_not_installed(mods, &r#mod, subject, route)?;

        log::info!("Extracting archive...");
        extract_archive(archive, mod_dir.clone(), root).await.install_step(subject, InstallStep::Extract)?;

        log::debug!("Detecting patch file layout...");
        let warning = apply_patch_layout(&mod_dir, &mut r#mod.manifest)
            .await
            .install_step(subject, InstallStep::FindPatchFiles)?;
        Ok((r#mod, warning))
    }
    .await;
    let (mut r#mod, warning) = match prepared {
        Ok(v) => v,
        Err(e) => {
            if let Err(cleanup) = mod_folder::remove_mod_folder(&mods_root, &mod_dir).await {
                log::error!("Failed to clean up {:?} after a failed install: {:#}", mod_dir, cleanup);
            }
            return Err(e);
        }
    };

    log::debug!("Normalizing paths...");
    if let Err(e) = r#mod.normalize_paths().await {
        log::error!("Path normalization failed: {}", e);
    }

    r#mod.resolve_sources().await;

    mods.push(r#mod.clone());
    log::info!("Mod successfully added.");
    Ok((r#mod, warning))
}

/// Whether installing `archive` will use a manifest.json from it: one at
/// its root, or a readable one inside a wrapper folder (a broken one there
/// is ignored, see [`resolve_manifest`]). An unreadable archive counts as
/// "has one": resolving the manifest then reports the real problem.
fn archive_has_manifest(archive: &mut Archive) -> bool {
    match crate::mod_root::find_archive_manifest(archive) {
        Ok(None) => false,
        Ok(Some((root, entry))) if !root.as_os_str().is_empty() => match archive.read_path(&entry) {
            Ok(data) => Manifest::parse(&data, "manifest.json").is_ok(),
            Err(_) => true,
        },
        _ => true,
    }
}

/// Reading the manifest out of an archive fails either because the
/// archive can't be read (encrypted, damaged, an unsupported method: an
/// extraction problem) or because the manifest itself is broken.
fn manifest_failure(subject: &str, e: anyhow::Error) -> InstallError {
    let step = if crate::archive::is_archive_problem(&e) { InstallStep::Extract } else { InstallStep::ReadManifest };
    InstallError::new(subject, step, e)
}

/// Refuse a mod whose GUID is already in the mod list, saying which mod
/// has it and what to do: the same mod again, or -- when the names differ
/// -- a different mod whose author reused another mod's manifest.json.
///
/// An archive added on the Mods page never gets here with such an ID: the
/// user is asked whether to replace the installed mod instead (see
/// [`decide_replace`]). It does when the question couldn't be asked, or in
/// the bulk import for a row that wasn't offered (or ticked) as a replace
/// (see `mod_import::ItemStatus::ReplaceInstalled`), so the hint says how
/// to get it.
/// How a mod is being added, for [`check_not_installed`]'s hint.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum AddRoute {
    /// An archive added one by one (Add, drop, Add URL, a browser install).
    Archive,
    /// An archive in the bulk import, which never asks: it replaces only
    /// what the user ticked as a replace in its list.
    Import,
    Folder,
}

fn check_not_installed(mods: &[Mod], new: &Mod, subject: &str, route: AddRoute) -> Result<(), InstallError> {
    let Some(existing) = mods.iter().find(|m| m.guid() == new.guid()) else {
        return Ok(());
    };
    let cause = anyhow::anyhow!(
        "its manifest.json gives it the ID (GUID) {{{}}}, and \"{}\" in your mod list already has that ID",
        new.guid(),
        existing.name()
    );
    let same_name = existing.name().trim().eq_ignore_ascii_case(new.name().trim());
    let how = match route {
        AddRoute::Archive => Some("add the file again with DDMM's Mods page open and choose Replace when asked"),
        AddRoute::Import => Some(
            "add the file on its own with Add (or drop it on the Mods page) and choose Replace when asked (the import \
             list only offers to replace a mod when it can tell the file differs from the one installed)",
        ),
        AddRoute::Folder => None,
    };
    let hint = if let (true, Some(how)) = (same_name, how) {
        format!(
            "\"{}\" is already installed. To replace it with this file, {how} (or use Update on it, or remove it \
             first).",
            existing.name()
        )
    } else if let Some(how) = how {
        format!(
            "Two different mods can't share an ID: the mod's author probably copied another mod's manifest.json, \
             so let them know. To install it anyway, {how} (that removes \"{}\"), or extract this archive, \
             delete its manifest.json, and add the extracted folder with Add Folder (DDMM then gives it an ID of \
             its own).",
            existing.name()
        )
    } else if same_name {
        format!(
            "\"{}\" is already installed. To replace it with this folder, remove it first (or use Update on it).",
            existing.name()
        )
    } else {
        format!(
            "Two different mods can't share an ID: the mod's author probably copied another mod's manifest.json, \
             so let them know. To install it anyway, remove \"{}\" first, or extract this archive, delete its \
             manifest.json, and add the extracted folder with Add Folder (DDMM then gives it an ID of its own).",
            existing.name()
        )
    };
    Err(InstallError::new(subject, InstallStep::Register, cause).with_hint(hint))
}

#[tauri::command]
pub async fn add_mods(app: AppHandle, state: State<'_, AppState>, archive_files: Vec<PathBuf>) -> TAResult<Vec<TAResult<InstalledMod>>> {
    let _data_op = state.data_op().into_ta_result()?;
    if state.mods.lock().await.is_none() {
        return anyhow::anyhow!("mods not read").into_ta_result();
    }

    log::info!("Adding {} mod(s)...", archive_files.len());

    // One after another through the single-archive install, so every file
    // gets exactly the same checks, questions, cleanup and error messages
    // as Add; a failure only affects its own file.
    let asker = Asker::in_app(&app);
    let mut results = Vec::with_capacity(archive_files.len());
    for archive_file in &archive_files {
        let result = add_archive(&state, archive_file, &asker).await;
        log::info!(" - {:?} : {}", archive_file, if result.is_ok() { "Ok" } else { "Err" });
        results.push(result);
    }

    Ok(results)
}

/// Create a new, empty folder in `mods_root` to install `source` (an
/// archive file or a folder) into, and return it with its name.
///
/// The name is `wanted` made safe with [`mod_folder::safe_folder_name`]
/// (so `.`, `..`, separators, reserved names and the like can never name
/// anything but a single new folder), or -- when a file or folder of that
/// name is already there -- `wanted (2)`, `wanted (3)`, ... An existing
/// folder is never deleted or reused: it may be another mod, or something
/// the user put there by hand.
///
/// Refuses first if `source` and the folder overlap -- copying into it
/// would then copy the source into itself.
async fn prepare_mod_dir(
    source: &Path,
    mods_root: &Path,
    wanted: &str,
    subject: &str,
) -> Result<(PathBuf, String), InstallError> {
    let step = InstallStep::PrepareFolder;
    tokio::fs::create_dir_all(mods_root).await.install_step(subject, step)?;
    let base = mod_folder::safe_folder_name(wanted);
    for n in 1..=10_000usize {
        let name = if n == 1 { base.clone() } else { mod_folder::numbered(&base, n) };
        let mod_dir = mods_root.join(&name);
        mod_folder::ensure_mod_folder(mods_root, &mod_dir).install_step(subject, step)?;
        if crate::fs_util::path_overlap(source, &mod_dir).install_step(subject, step)?.is_some() {
            return Err(InstallError::new(
                subject,
                step,
                anyhow::anyhow!(
                    "it is inside (or is) the folder DDMM would install it into ({:?})",
                    mod_dir
                ),
            )
            .with_hint("Move it somewhere outside DDMM's mod storage and add it from there."));
        }
        // `create_dir`, not `create_dir_all`: it fails if the folder is
        // already there, so nothing that exists is ever taken over.
        match tokio::fs::create_dir(&mod_dir).await {
            Ok(()) => return Ok((mod_dir, name)),
            Err(e) if e.kind() == std::io::ErrorKind::AlreadyExists => {
                log::info!("{:?} already exists; leaving it alone and trying the next free name.", mod_dir);
            }
            Err(e) => return Err(InstallError::new(subject, step, e)),
        }
    }
    Err(InstallError::new(
        subject,
        step,
        anyhow::anyhow!("no free folder name for \"{}\" in DDMM's mod storage", base),
    ))
}

/// For a mod without a manifest.json (so no ID to tell mods apart): refuse
/// when the folder it would get is already a mod in the list. Adding the
/// same manifest-less file twice is by far the likeliest reason, and a
/// second copy as "Name (2)" would only get in the way.
fn refuse_if_listed(mods: &[Mod], mods_root: &Path, wanted: &str, subject: &str) -> Result<(), InstallError> {
    use crate::fs_util::{path_overlap, PathOverlap};
    let dir = mods_root.join(mod_folder::safe_folder_name(wanted));
    let Some(existing) = mods
        .iter()
        .find(|m| matches!(path_overlap(&m.directory, &dir), Ok(Some(PathOverlap::Same))))
    else {
        return Ok(());
    };
    Err(InstallError::new(
        subject,
        InstallStep::Register,
        anyhow::anyhow!(
            "\"{}\" is already installed (it's in your mod list), and this file has no manifest.json to tell \
             whether it's a different mod",
            existing.name()
        ),
    )
    .with_hint(format!(
        "To replace \"{}\" with this file, use Update on it (or remove it first). If it's a different mod that \
         just has the same file name, rename the file and add it again.",
        existing.name()
    )))
}

/// The name a mod without a manifest.json is listed under: the name it was
/// added as, unless nothing readable is left of that (such as a file called
/// `..zip`), in which case its folder's name.
fn display_name(wanted: &str, folder_name: &str) -> String {
    let trimmed = wanted.trim_matches(|c: char| c == '.' || c.is_whitespace());
    if trimmed.is_empty() { folder_name.to_string() } else { wanted.trim().to_string() }
}

/// Whether a folder in the mod storage is one of DDMM's hidden working
/// folders (its name starts with a dot) rather than a mod.
fn is_hidden_name(name: &std::ffi::OsStr) -> bool {
    name.to_string_lossy().starts_with('.')
}

/// Generate the same "no manifest present" local legacy manifest, whether
/// the mod came from an archive with no `manifest.json`, or a plain folder
/// with no `manifest.json`.
fn generate_local_manifest(name: String) -> anyhow::Result<Manifest> {
    let mut guid = [0u8; 16];
    guid[..5].copy_from_slice(b"LOCAL");
    SysRng.try_fill_bytes(&mut guid[5..])?;

    Ok(Manifest::Legacy(legacy::Manifest {
        guid: Uuid::from_bytes(guid),
        name,
        description: String::new(),
        icon_path: None,
        options: None,
    }))
}

/// Also returns the mod's root inside the archive: empty, or the wrapper
/// folder(s) holding the manifest.json (see [`crate::mod_root`]).
async fn resolve_manifest(mut archive: Archive, name: String, manifest_file: PathBuf) -> anyhow::Result<(Archive, Manifest, PathBuf)> {
    let found = crate::mod_root::find_archive_manifest(&mut archive)?;
    if let Some((root, entry)) = found {
        let manifest_data = archive.read_path(&entry)?;
        match Manifest::parse(&manifest_data, &entry.to_string_lossy()) {
            Ok(manifest) => return Ok((archive, manifest, root)),
            // A broken manifest.json inside a wrapper folder: install the
            // archive the way DDMM always did (it was never read before),
            // rather than fail. One at the root is still an error.
            Err(e) if !root.as_os_str().is_empty() => {
                log::warn!("Ignoring {:?}, which can't be read ({:#}); installing without it.", entry, e);
            }
            Err(e) => return Err(e),
        }
    }
    let manifest = generate_local_manifest(name)?;

    let manifest_data = serde_json::to_vec_pretty(&manifest)?;
    tokio::fs::write(&manifest_file, manifest_data)
        .await
        .with_context(|| format!("couldn't write {:?}", manifest_file))?;

    Ok((archive, manifest, PathBuf::new()))
}

/// Same idea as [`resolve_manifest`], but for a plain folder install: read
/// `manifest.json` from the source folder if present, otherwise generate a
/// local one and write it straight into the (already-created) destination
/// mod directory.
async fn resolve_manifest_for_dir(source_dir: &Path, name: String, manifest_file: PathBuf) -> anyhow::Result<Manifest> {
    let source_manifest = find_manifest_file(source_dir).await;
    if let Some(source_manifest) = source_manifest {
        let manifest_data = tokio::fs::read(&source_manifest)
            .await
            .with_context(|| format!("couldn't read {:?}", source_manifest))?;
        let manifest = Manifest::parse(&manifest_data, &source_manifest.to_string_lossy())?;
        Ok(manifest)
    } else {
        let manifest = generate_local_manifest(name)?;

        let manifest_data = serde_json::to_vec_pretty(&manifest)?;
        tokio::fs::write(&manifest_file, manifest_data)
            .await
            .with_context(|| format!("couldn't write {:?}", manifest_file))?;

        Ok(manifest)
    }
}

/// Extract `archive` into `mod_dir`. When the mod's `root` is a wrapper
/// folder inside the archive, only that folder's contents end up in
/// `mod_dir` (the rest -- the wrapper itself, OS clutter, a loose readme
/// beside it -- is dropped).
async fn extract_archive(mut archive: Archive, mod_dir: PathBuf, root: PathBuf) -> anyhow::Result<()> {
    if root.as_os_str().is_empty() {
        let dir = mod_dir.clone();
        tokio::task::spawn_blocking(move || archive.extract_to(dir)).await??;
    } else {
        log::info!("The archive's manifest.json is in {:?}; installing that folder's contents.", root);
        // Unpacked next to the mod folder (a dot-name, never loaded as a
        // mod; swept on the next start if DDMM stops halfway), then the
        // wrapped folder takes the reserved, still empty, mod folder's
        // place in one rename.
        let mods_root = mod_dir.parent().ok_or_else(|| anyhow::anyhow!("{:?} has no parent folder", mod_dir))?.to_path_buf();
        let unpacked = mods_root.join(format!("{}{}", mod_folder::UNWRAP_PREFIX, Uuid::new_v4()));
        tokio::fs::create_dir(&unpacked).await?;
        let moved: anyhow::Result<()> = async {
            let dir = unpacked.clone();
            tokio::task::spawn_blocking(move || archive.extract_to(dir)).await??;
            tokio::fs::remove_dir(&mod_dir).await.with_context(|| format!("couldn't replace {:?}", mod_dir))?;
            crate::fs_util::move_path(&unpacked.join(&root), &mod_dir).await
        }
        .await;
        // Only what was left around the wrapped folder (or, on a failure,
        // the unpacked copy): a cleanup that fails never undoes the install.
        if let Err(e) = mod_folder::remove_mod_folder(&mods_root, &unpacked).await {
            log::warn!("Couldn't remove the working folder {:?} yet (removed on the next start): {:#}", unpacked, e);
        }
        moved?;
    }
    normalize_manifest_file_name(&mod_dir).await
}

/// `dir`'s manifest file: `manifest.json`, or failing that a case variant
/// such as `Manifest.json` (fine on Windows, invisible to an exact lookup
/// on Linux's case-sensitive filesystems).
async fn find_manifest_file(dir: &Path) -> Option<PathBuf> {
    let exact = dir.join(MANIFEST_FILE);
    if exact.is_file() {
        return Some(exact);
    }
    let mut entries = tokio::fs::read_dir(dir).await.ok()?;
    while let Ok(Some(entry)) = entries.next_entry().await {
        if entry.file_name().to_string_lossy().eq_ignore_ascii_case(MANIFEST_FILE)
            && entry.file_type().await.map(|t| t.is_file()).unwrap_or(false)
        {
            return Some(entry.path());
        }
    }
    None
}

/// After extracting/copying a mod, rename a `Manifest.json`-style case
/// variant to exactly `manifest.json`, which is what loading the library
/// looks for -- otherwise, on Linux, the mod would disappear on restart.
async fn normalize_manifest_file_name(mod_dir: &Path) -> anyhow::Result<()> {
    let exact = mod_dir.join(MANIFEST_FILE);
    if exact.is_file() {
        return Ok(());
    }
    if let Some(variant) = find_manifest_file(mod_dir).await {
        log::info!("Renaming {:?} to {:?}", variant, exact);
        crate::fs_util::move_path(&variant, &exact).await?;
    }
    Ok(())
}

/// Install a mod from a plain, already-unpacked folder: `folder` becomes the
/// mod's source, its `manifest.json` is used if present (otherwise a local
/// one is generated), and its contents are copied (not moved, symlinks not
/// followed) into the managed mod directory.
///
/// `folder` must not overlap DDMM's own mod storage (`<data>/mods`), which
/// is checked before anything on disk is touched:
/// - the storage folder itself, a folder containing it (such as DDMM's data
///   folder in a portable install), or a folder deeper inside an installed
///   mod is refused with an explanation -- copying any of those would copy
///   the folder into itself, over and over, until the disk is full;
/// - a mod folder sitting directly in the storage folder is adopted in
///   place ([`adopt_folder_in_place`]): nothing is copied, it just gets a
///   manifest and joins the mod list.
///
/// Mirrors [`install_from_archive`]'s locking contract: takes the
/// already-locked mods vector, never locks anything itself.
async fn install_from_folder(base_path: &Path, mods: &mut Vec<Mod>, folder: &Path) -> TAResult<(Mod, Option<String>)> {
    let (mut r#mod, warning) = install_from_folder_as(base_path, mods, folder, None).await?;
    let folder_name = crate::fs_util::resolve_path(folder)
        .ok()
        .and_then(|p| p.file_name().and_then(|n| n.to_str()).map(str::to_string));
    if let Some(folder_name) = folder_name {
        record_nexus_from_file_name(mods, &mut r#mod, &folder_name, false).await;
    }
    Ok((r#mod, warning))
}

/// [`install_from_folder`], optionally into `mods/<name>` instead of a
/// folder named after the source folder (the bulk import picks unique
/// names itself).
pub(crate) async fn install_from_folder_as(
    base_path: &Path,
    mods: &mut Vec<Mod>,
    folder: &Path,
    name_override: Option<&str>,
) -> TAResult<(Mod, Option<String>)> {
    log::info!("Adding mod from folder {:?}...", folder);
    let subject = subject_of(folder);
    install_folder_steps(base_path, mods, folder, name_override, &subject).await.map_err(report)
}

async fn install_folder_steps(
    base_path: &Path,
    mods: &mut Vec<Mod>,
    folder: &Path,
    name_override: Option<&str>,
    subject: &str,
) -> Result<(Mod, Option<String>), InstallError> {
    let refuse = |cause: anyhow::Error| InstallError::new(subject, InstallStep::PrepareFolder, cause);

    if !folder.is_dir() {
        return Err(refuse(anyhow::anyhow!("{:?} is not a folder (or no longer exists)", folder)));
    }

    let mods_root = base_path.join(MODS_DIRECTORY);
    let resolved = crate::fs_util::resolve_path(folder).install_step(subject, InstallStep::PrepareFolder)?;

    let name = resolved
        .file_name()
        .and_then(|n| n.to_str())
        .map(str::to_string)
        .ok_or_else(|| refuse(anyhow::anyhow!("the folder's name can't be read")))?;

    use crate::fs_util::{path_overlap, PathOverlap};
    match path_overlap(&resolved, &mods_root).install_step(subject, InstallStep::PrepareFolder)? {
        None => {}
        Some(PathOverlap::Same) => {
            return Err(refuse(anyhow::anyhow!(
                "That folder is DDMM's own mod storage ({}), so there is nothing to copy. \
                 Mods in it that have a manifest.json are already in your mod list. To add a \
                 mod folder that is in there without one, pick that mod's own folder instead: \
                 DDMM will set it up where it is, without copying it.",
                mods_root.display()
            )));
        }
        Some(PathOverlap::SecondInsideFirst) => {
            return Err(refuse(anyhow::anyhow!(
                "DDMM can't add {}: DDMM's own mod storage ({}) is inside it, so adding it would \
                 copy the folder into itself. Pick a single mod's folder instead.",
                folder.display(),
                mods_root.display()
            )));
        }
        Some(PathOverlap::FirstInsideSecond) => {
            let directly_in_storage = resolved
                .parent()
                .map(|parent| matches!(path_overlap(parent, &mods_root), Ok(Some(PathOverlap::Same))))
                .unwrap_or(false);
            if directly_in_storage && name_override.is_none() {
                if name.starts_with('.') {
                    return Err(refuse(anyhow::anyhow!(
                        "folders in DDMM's mod storage whose names start with a dot are DDMM's own working \
                         folders (for example a copy left behind by an interrupted update), not mods"
                    ))
                    .with_hint("Rename the folder so its name doesn't start with a dot, then add it again."));
                }
                let display_name = crate::mod_import::display_name_from_file(&name, false);
                return adopt_folder_in_place(mods, &mods_root.join(&name), &display_name, subject).await;
            }
            return Err(refuse(anyhow::anyhow!(
                "{} is inside a mod folder in DDMM's mod storage ({}). Pick that mod's own \
                 folder (the one directly inside the storage folder), or a folder outside it.",
                folder.display(),
                mods_root.display()
            )));
        }
    }

    // The folder keeps the source folder's name; a generated manifest gets
    // a readable one (no Nexus download suffix).
    let manifest_name = name_override
        .map(str::to_string)
        .unwrap_or_else(|| crate::mod_import::display_name_from_file(&name, false));
    let name = name_override.map(str::to_string).unwrap_or(name);
    // A folder that only wraps the mod's folder (`Download/ModName/manifest.json`):
    // install the inner folder, so the author's manifest is used.
    let folder = &crate::mod_root::folder_mod_root(folder);
    log::info!("Preparing mod directory...");
    if find_manifest_file(folder).await.is_none() {
        refuse_if_listed(mods, &mods_root, &name, subject)?;
    }
    let (mod_dir, folder_name) = prepare_mod_dir(folder, &mods_root, &name, subject).await?;
    let manifest_name = display_name(&manifest_name, &folder_name);
    let manifest_file = mod_dir.join(MANIFEST_FILE);

    // From here on `mod_dir` is a folder we just created (and, per the
    // checks above, not the source or anywhere near it), so a failure must
    // remove it again rather than leave a half-copied mod behind.
    let result = install_from_folder_inner(mods, folder, &manifest_name, &mod_dir, &manifest_file, subject).await;

    if result.is_err() {
        if let Err(cleanup) = mod_folder::remove_mod_folder(&mods_root, &mod_dir).await {
            log::error!("Failed to clean up {:?} after a failed install: {:#}", mod_dir, cleanup);
        }
    }

    result
}

/// Register a folder that already sits directly in DDMM's mod storage as a
/// mod, without copying it: its own `manifest.json` is used if it has one,
/// otherwise a local one is generated and written into it (and removed
/// again if registering fails). Nothing else in the folder is touched, and
/// the folder is never deleted.
///
/// A folder that only wraps the mod's own folder (`mods/My Mod/My Mod/manifest.json`)
/// is first unwrapped where it is ([`unwrap_adopted_folder`]), so the mod
/// gets its author's manifest, as it would from the zipped folder.
async fn adopt_folder_in_place(
    mods: &mut Vec<Mod>,
    mod_dir: &Path,
    name: &str,
    subject: &str,
) -> Result<(Mod, Option<String>), InstallError> {
    use crate::fs_util::{path_overlap, PathOverlap};

    log::info!("{:?} is already in the mod storage; adopting it in place.", mod_dir);

    if let Some(existing) = mods
        .iter()
        .find(|m| matches!(path_overlap(&m.directory, mod_dir), Ok(Some(PathOverlap::Same))))
    {
        return Err(InstallError::new(
            subject,
            InstallStep::Register,
            anyhow::anyhow!("\"{}\" is already installed (it's in your mod list)", existing.name()),
        ));
    }

    let mut unwrapped = None;
    if find_manifest_file(mod_dir).await.is_none() {
        if let Some(root) = crate::mod_root::folder_root_components(mod_dir) {
            let shown = root.join("/");
            unwrap_adopted_folder(mods, mod_dir, root, subject).await?;
            unwrapped = Some(shown);
        }
    }

    let manifest_file = mod_dir.join(MANIFEST_FILE);
    let had_manifest = find_manifest_file(mod_dir).await.is_some();

    let result: Result<(Mod, Option<String>), InstallError> = async {
        let manifest = resolve_manifest_for_dir(mod_dir, name.to_string(), manifest_file.clone())
            .await
            .install_step(subject, InstallStep::ReadManifest)?;
        let mut r#mod = Mod {
            manifest,
            directory: mod_dir.to_path_buf(),
            sources: Vec::new(),
        };

        check_not_installed(mods, &r#mod, subject, AddRoute::Folder)?;

        normalize_manifest_file_name(mod_dir).await.install_step(subject, InstallStep::ReadManifest)?;
        let warning = apply_patch_layout(mod_dir, &mut r#mod.manifest)
            .await
            .install_step(subject, InstallStep::FindPatchFiles)?;
        Ok((r#mod, warning))
    }
    .await;

    let (mut r#mod, warning) = match result {
        Ok(v) => v,
        Err(e) => {
            if !had_manifest {
                let _ = tokio::fs::remove_file(&manifest_file).await;
            }
            // Not moved back: the folder is already laid out as the
            // author's mod, and adding it again picks up from there.
            return Err(match unwrapped {
                Some(shown) => e.add_hint(format!(
                    "Before this, DDMM had already moved the contents of \"{shown}\" up into the mod's folder (that's \
                     how it sets up a mod folder wrapped in another one); that stays as it is. Adding the folder again \
                     continues from there."
                )),
                None => e,
            });
        }
    };

    if let Err(e) = r#mod.normalize_paths().await {
        log::error!("Path normalization failed: {}", e);
    }
    r#mod.resolve_sources().await;

    mods.push(r#mod.clone());
    log::info!("Mod adopted in place.");
    Ok((r#mod, warning))
}

/// Move the mod's root of a wrapped folder in the mod storage (the
/// wrapper folders `root` inside `mod_dir`) up into `mod_dir`, with
/// whatever was next to the wrapper folders (see
/// [`crate::mod_root::unwrap_in_place`]). The mod keeps the folder it is
/// in, so that folder stays the one place it lives in for deploy, update,
/// replace and delete.
///
/// Refused, with nothing changed, when the author's manifest.json carries
/// the ID of a mod already in the list, or when something next to the
/// wrapper folders has the same name as something in the mod's root.
async fn unwrap_adopted_folder(mods: &[Mod], mod_dir: &Path, root: Vec<String>, subject: &str) -> Result<(), InstallError> {
    let shown = root.join("/");
    let inner = mod_dir.join(root.iter().collect::<PathBuf>());
    let manifest_path = find_manifest_file(&inner)
        .await
        .ok_or_else(|| anyhow::anyhow!("{:?} has no manifest.json", inner))
        .install_step(subject, InstallStep::ReadManifest)?;
    let data = tokio::fs::read(&manifest_path)
        .await
        .with_context(|| format!("couldn't read {:?}", manifest_path))
        .install_step(subject, InstallStep::ReadManifest)?;
    let manifest = Manifest::parse(&data, &manifest_path.to_string_lossy()).install_step(subject, InstallStep::ReadManifest)?;
    let candidate = Mod { manifest, directory: mod_dir.to_path_buf(), sources: Vec::new() };
    check_not_installed(mods, &candidate, subject, AddRoute::Folder)?;

    let clash = {
        let (dir, root) = (mod_dir.to_path_buf(), root.clone());
        tokio::task::spawn_blocking(move || crate::mod_root::in_place_clash(&dir, &root))
            .await
            .map_err(anyhow::Error::from)
            .and_then(|r| r.map_err(anyhow::Error::from))
            .install_step(subject, InstallStep::PrepareFolder)?
    };
    if let Some(name) = clash {
        return Err(InstallError::new(
            subject,
            InstallStep::PrepareFolder,
            anyhow::anyhow!(
                "its mod files and manifest.json are in the folder \"{shown}\" inside it, and \"{name}\" next to \
                 that folder has the same name as something in it"
            ),
        )
        .with_hint(format!(
            "DDMM sets the mod up by moving the contents of \"{shown}\" up into the mod's folder, together with \
             what's next to it. Rename or remove one of the two \"{name}\", then add the folder again. Nothing was \
             changed."
        )));
    }

    log::info!("{:?} wraps its mod's folder {:?}; moving that folder's contents up.", mod_dir, shown);
    let mods_root = mod_dir
        .parent()
        .map(Path::to_path_buf)
        .ok_or_else(|| anyhow::anyhow!("{:?} has no parent folder", mod_dir))
        .install_step(subject, InstallStep::PrepareFolder)?;
    let dir = mod_dir.to_path_buf();
    use crate::mod_root::UnwrapFailure;
    let result = match tokio::task::spawn_blocking(move || crate::mod_root::unwrap_in_place(&mods_root, &dir, &root)).await {
        Ok(result) => result,
        // The move stopped somewhere unknown: don't claim nothing changed.
        Err(e) => {
            return Err(InstallError::new(subject, InstallStep::PrepareFolder, anyhow::Error::from(e)).with_hint(
                "DDMM stopped partway through moving the folder's files. Restart DDMM: on the next start it either \
                 finishes setting the folder up or puts it back as it was. Then add the folder again if it isn't in \
                 your mod list.",
            ));
        }
    };
    match result {
        Ok(()) => Ok(()),
        Err(UnwrapFailure::Unchanged(error)) => {
            let hint = unwrap_refused_hint(&error);
            Err(InstallError::new(subject, InstallStep::PrepareFolder, error).with_hint(hint))
        }
        Err(UnwrapFailure::SetAside { stage, error }) => {
            let hidden = stage.file_name().map(|n| n.to_string_lossy().into_owned()).unwrap_or_default();
            let folder = mod_dir.file_name().map(|n| n.to_string_lossy().into_owned()).unwrap_or_default();
            Err(InstallError::new(subject, InstallStep::PrepareFolder, error).with_hint(format!(
                "The folder couldn't be moved back yet: its files are safe in the hidden folder \"{hidden}\" in \
                 DDMM's mod storage. Restart DDMM and it puts them back as \"{folder}\", as they were; then add the \
                 folder again."
            )))
        }
    }
}

/// The hint when moving a wrapped folder's files up was refused before
/// anything changed: a file in use (Windows), missing permissions, or
/// anything else.
fn unwrap_refused_hint(error: &anyhow::Error) -> &'static str {
    let io_errors = || error.chain().filter_map(|e| e.downcast_ref::<std::io::Error>());
    // 5: access denied, 32: sharing violation, 33: lock violation -- the
    // codes Windows gives for a file another program has open.
    if cfg!(windows) && io_errors().any(|io| matches!(io.raw_os_error(), Some(5 | 32 | 33))) {
        return "Nothing was changed. A file in the folder is in use: close Helldivers 2 and any window showing \
                that folder or a file from it (such as File Explorer), then add the folder again.";
    }
    if io_errors().any(|io| io.kind() == std::io::ErrorKind::PermissionDenied) {
        return "Nothing was changed. DDMM isn't allowed to rename things in that folder: check that you own it and \
                can write to it (and to DDMM's mod storage), then add the folder again.";
    }
    "Nothing was changed. Try adding the folder again."
}

async fn install_from_folder_inner(
    mods: &mut Vec<Mod>,
    folder: &Path,
    name: &str,
    mod_dir: &Path,
    manifest_file: &Path,
    subject: &str,
) -> Result<(Mod, Option<String>), InstallError> {
    log::info!("Resolving manifest...");
    let manifest = resolve_manifest_for_dir(folder, name.to_string(), manifest_file.to_path_buf())
        .await
        .install_step(subject, InstallStep::ReadManifest)?;

    let mut r#mod = Mod {
        manifest,
        directory: mod_dir.to_path_buf(),
        sources: Vec::new(),
    };

    log::info!("Checking for duplicate...");
    check_not_installed(mods, &r#mod, subject, AddRoute::Folder)?;

    log::info!("Copying folder contents...");
    copy_dir_recursive(folder, mod_dir, &[sources::ORIGIN_SIDECAR_FILE])
        .await
        .map_err(|e| {
            // Same plain-language treatment as an archive's I/O errors
            // (disk full, access denied, path too long).
            match e.downcast::<std::io::Error>() {
                Ok(io) => crate::archive::io_error(io, "copying a file failed"),
                Err(e) => e,
            }
        })
        .install_step(subject, InstallStep::Copy)?;
    normalize_manifest_file_name(mod_dir).await.install_step(subject, InstallStep::Copy)?;

    log::debug!("Detecting patch file layout...");
    let warning = apply_patch_layout(mod_dir, &mut r#mod.manifest)
        .await
        .install_step(subject, InstallStep::FindPatchFiles)?;

    log::debug!("Normalizing paths...");
    if let Err(e) = r#mod.normalize_paths().await {
        log::error!("Path normalization failed: {}", e);
    }

    r#mod.resolve_sources().await;

    mods.push(r#mod.clone());
    log::info!("Mod successfully added.");
    Ok((r#mod, warning))
}

#[tauri::command]
pub async fn add_mod_folder(state: State<'_, AppState>, folder: PathBuf) -> TAResult<InstalledMod> {
    let _data_op = state.data_op().into_ta_result()?;
    let mut mods = state.mods.lock().await;
    if mods.is_none() {
        return anyhow::anyhow!("mods not read").into_ta_result();
    }
    let mods = mods.as_mut().unwrap();

    let (r#mod, warning) = install_from_folder(&state.base_path, mods, &folder).await?;
    Ok(InstalledMod::added(r#mod, warning))
}

/// Install any mix of archive files and plain folders in one go, dispatching
/// each path to the right installer. Each path locks the mods mutex
/// independently, so one item's failure never blocks the rest and nothing
/// ever nests a lock inside another lock.
#[tauri::command]
pub async fn add_paths(app: AppHandle, state: State<'_, AppState>, paths: Vec<PathBuf>) -> TAResult<Vec<TAResult<InstalledMod>>> {
    let _data_op = state.data_op().into_ta_result()?;
    log::info!("Adding mods from {} path(s)...", paths.len());
    let asker = Asker::in_app(&app);

    let mut results = Vec::with_capacity(paths.len());
    for path in paths {
        let is_dir = tokio::fs::metadata(&path)
            .await
            .map(|m| m.is_dir())
            .unwrap_or(false);

        let result = if is_dir {
            let mut mods = state.mods.lock().await;
            match mods.as_mut() {
                Some(mods) => install_from_folder(&state.base_path, mods, &path)
                    .await
                    .map(|(r#mod, warning)| InstalledMod::added(r#mod, warning)),
                None => anyhow::anyhow!("mods not read").into_ta_result(),
            }
        } else if state.mods.lock().await.is_none() {
            anyhow::anyhow!("mods not read").into_ta_result()
        } else {
            add_archive(&state, &path, &asker).await
        };

        results.push(result);
    }

    Ok(results)
}

/// Install a mod by downloading an archive from a direct `https://` URL
/// first (into a throwaway temp directory), then running it through the
/// same install path as a locally picked archive file. Records where the
/// mod came from in a `.hd2mm-origin.json` sidecar next to the mod, without
/// ever touching the author's own `manifest.json`.
#[tauri::command]
pub async fn add_mod_from_url(app: AppHandle, state: State<'_, AppState>, url: String) -> TAResult<InstalledMod> {
    let _data_op = state.data_op().into_ta_result()?;
    log::info!("Downloading mod from {}...", download::redact_url(&url));

    let staging_root = state.base_path.join(download::STAGING_DIRECTORY);
    let downloaded = match download::download_archive(&url, &staging_root).await {
        Ok(d) => d,
        Err(e) => {
            let subject = download::redact_url(&url);
            let mut err = InstallError::new(subject, InstallStep::Download, e);
            if format!("{err}").contains("not a supported archive") {
                err = err.with_hint(
                    "The link doesn't lead straight to the file. Download the mod from its page in your browser, \
                     then add the downloaded file with Add.",
                );
            }
            return Err(report(err));
        }
    };

    let install_result = if state.mods.lock().await.is_none() {
        anyhow::anyhow!("mods not read").into_ta_result()
    } else {
        add_archive(&state, &downloaded.path, &Asker::in_app(&app)).await
    };

    // The staged download (and its throwaway parent directory) is no longer
    // needed either way -- the archive contents were copied out on success,
    // and a mod the user kept is left as it is.
    let _ = tokio::fs::remove_dir_all(&downloaded.temp_dir).await;

    let installed = install_result?;
    if installed.kept {
        return Ok(installed);
    }
    let InstalledMod { mut r#mod, warning, replaced, .. } = installed;

    log::info!("Recording install origin...");
    let mut origin_source = sources::source_from_page_url(&url).unwrap_or_else(|| Source {
        provider: sources::provider_from_url(&url),
        id: None,
        url: Some(url.clone()),
        version: None,
    });
    // A GitHub release-asset link names its release: record that as the
    // installed version, so update checks work for this mod right away.
    let mut installed_files = Vec::new();
    if let Some(tag) = sources::github_tag_from_download_url(&url) {
        origin_source.version = Some(tag);
        installed_files.push(sources::InstalledFile {
            provider: "github".to_string(),
            file_name: url.rsplit('/').next().map(|n| {
                percent_encoding::percent_decode_str(n.split(['?', '#']).next().unwrap_or(n))
                    .decode_utf8_lossy()
                    .into_owned()
            }),
            ..Default::default()
        });
    }
    if let Err(e) =
        sources::write_origin_sidecar_with_files(&r#mod.directory, vec![origin_source], installed_files).await
    {
        log::error!("Failed to write origin sidecar: {}", e);
    }

    r#mod.resolve_sources().await;

    {
        let mut mods = state.mods.lock().await;
        if let Some(mods) = mods.as_mut() {
            if let Some(existing) = mods.iter_mut().find(|m| m.guid() == r#mod.guid()) {
                *existing = r#mod.clone();
            }
        }
    }

    Ok(InstalledMod { r#mod, warning, replaced, kept: false })
}

/// Install `archive_path` as an update of the existing mod `existing_guid`,
/// used by both the browser handoff and the "Update from {site}" flow.
///
/// The new content is fully staged (extracted, manifest resolved, patch
/// layout detected) in a throwaway directory under the mods folder before
/// anything about the existing mod is touched. Only once that succeeds is
/// the old mod directory swapped out for the new one; on any failure before
/// the swap the old mod is left completely untouched, and the staging
/// directory is always cleaned up.
///
/// GUID handling: if the newly-installed manifest is one this manager
/// generated itself (no manifest.json in the update), the *old* GUID is
/// kept so existing profile configs referencing this mod keep working. If
/// the update ships its own manifest with its own GUID, that GUID is kept
/// instead (even if it differs from the old one) and the change is logged
/// -- profile configs are not migrated in that case.
pub(crate) async fn install_update_from_archive(
    state: &AppState,
    mods: &mut Vec<Mod>,
    archive_path: &Path,
    existing_guid: Uuid,
) -> TAResult<(Mod, Option<String>)> {
    log::info!("Updating mod {{{}}} from {:?}...", existing_guid, archive_path);
    let subject = subject_of(archive_path);
    install_update_steps(state, mods, archive_path, existing_guid, &subject, false).await.map_err(report)
}

/// The in-place swap shared by updates and [`replace_from_archive`]. With
/// `same_id_only`, a file whose manifest.json doesn't have `existing_guid`
/// is refused before anything is touched.
async fn install_update_steps(
    state: &AppState,
    mods: &mut Vec<Mod>,
    archive_path: &Path,
    existing_guid: Uuid,
    subject: &str,
    same_id_only: bool,
) -> Result<(Mod, Option<String>), InstallError> {
    let replace = InstallStep::Replace;
    let old_mod = mods
        .iter()
        .find(|m| m.guid() == existing_guid)
        .cloned()
        .ok_or_else(|| anyhow::anyhow!("the mod to update (GUID {{{}}}) is no longer in the mod list", existing_guid))
        .install_step(subject, replace)?;
    let old_dir = old_mod.directory.clone();
    let mods_root = state.base_path.join(MODS_DIRECTORY);
    // The old folder is moved aside and replaced below: make sure it really
    // is one mod's folder in the storage before anything is created.
    mod_folder::ensure_mod_folder(&mods_root, &old_dir).install_step(subject, replace)?;

    let staging_dir = mods_root.join(format!("{}{}", mod_folder::UPDATE_STAGING_PREFIX, Uuid::new_v4()));
    // Its record first: a staging folder left by a crash is then known to
    // be DDMM's own extraction, which the next start deletes.
    let staging_record = mod_folder::staging_record_path(&staging_dir);
    write_record_value(&staging_record, serde_json::json!({ "staging": true }))
        .await
        .install_step(subject, InstallStep::PrepareFolder)?;
    if let Err(e) = tokio::fs::create_dir_all(&staging_dir).await {
        let _ = tokio::fs::remove_file(&staging_record).await;
        return Err(e).install_step(subject, InstallStep::PrepareFolder);
    }
    let discard_staging = || async {
        match mod_folder::remove_mod_folder(&mods_root, &staging_dir).await {
            Ok(()) => {
                let _ = tokio::fs::remove_file(&staging_record).await;
            }
            // The record stays: the next start deletes the rest.
            Err(e) => log::error!("Couldn't remove the update's staging folder: {:#}", e),
        }
    };

    let staged = stage_update(&staging_dir, archive_path, subject).await;

    let (mut manifest, warning) = match staged {
        Ok(ok) => ok,
        Err(e) => {
            discard_staging().await;
            return Err(e);
        }
    };

    let final_guid = if is_local_generated(&manifest) {
        if let Manifest::Legacy(legacy) = &mut manifest {
            legacy.guid = existing_guid;
            // The generated manifest is named after the update's archive
            // file ("CoolMod-1.4.zip" -> "CoolMod-1"); it's the same mod, so
            // keep the name and description the user already knows it by.
            legacy.name = old_mod.name().to_string();
            legacy.description = match &old_mod.manifest {
                Manifest::Legacy(m) => m.description.clone(),
                Manifest::V1(m) => m.description.clone(),
                Manifest::V2(m) => m.description.clone(),
            };
        }
        existing_guid
    } else {
        let new_guid = match &manifest {
            Manifest::Legacy(m) => m.guid,
            Manifest::V1(m) => m.guid,
            Manifest::V2(m) => m.guid,
        };
        let taken_by = mods.iter().find(|m| m.guid() == new_guid && new_guid != existing_guid);
        if let (true, Some(other)) = (is_local_generated(&old_mod.manifest), taken_by) {
            // Installed without its manifest.json (so with an ID of DDMM's
            // own), now updated with its author's -- whose ID another mod
            // in the list already has. The mod keeps the ID it has, so
            // nothing changes for its profile entries.
            log::warn!(
                "Update for mod {{{}}} ships the ID {{{}}}, which \"{}\" already has; keeping {{{}}}.",
                existing_guid, new_guid, other.name(), existing_guid
            );
            match &mut manifest {
                Manifest::Legacy(m) => m.guid = existing_guid,
                Manifest::V1(m) => m.guid = existing_guid,
                Manifest::V2(m) => m.guid = existing_guid,
            }
            existing_guid
        } else if new_guid != existing_guid {
            // Keeping a new ID that another installed mod already has would
            // leave two mods with one ID (and deleting one of them by ID
            // could then hit the other's files): refuse before touching
            // anything.
            if let Some(other) = mods.iter().find(|m| m.guid() == new_guid) {
                let err = InstallError::new(
                    subject,
                    replace,
                    anyhow::anyhow!(
                        "its manifest.json gives it the ID (GUID) {{{}}}, and \"{}\" in your mod list already has that ID",
                        new_guid,
                        other.name()
                    ),
                )
                .with_hint(format!(
                    "This file doesn't look like an update of \"{}\": it carries the ID of \"{}\", a different mod \
                     in your list, so nothing was changed. Check that it's the right file; if it is, let the mod's \
                     author know that it reuses another mod's ID.",
                    old_mod.name(),
                    other.name()
                ));
                discard_staging().await;
                return Err(err);
            }
            log::info!(
                "Update for mod {{{}}} ships its own GUID {{{}}}; keeping the new one{}.",
                existing_guid,
                new_guid,
                if is_local_generated(&old_mod.manifest) {
                    " (the old one was DDMM's own; profile entries are moved over to it)"
                } else {
                    " (profile entries referencing the old GUID will no longer match)"
                }
            );
            new_guid
        } else {
            new_guid
        }
    };

    if same_id_only && final_guid != existing_guid {
        discard_staging().await;
        return Err(InstallError::new(
            subject,
            replace,
            anyhow::anyhow!(
                "its manifest.json now gives it the ID (GUID) {{{}}}, not {{{}}} (the ID of \"{}\")",
                final_guid,
                existing_guid,
                old_mod.name()
            ),
        )
        .with_hint(format!("The file changed after DDMM read it, so \"{}\" was left as it was. Add it again.", old_mod.name())));
    }

    // Persist the (possibly GUID-rewritten) manifest into staging before the swap.
    let manifest_data = match serde_json::to_vec_pretty(&manifest) {
        Ok(d) => d,
        Err(e) => {
            discard_staging().await;
            return Err(InstallError::new(subject, replace, e));
        }
    };
    if let Err(e) = tokio::fs::write(staging_dir.join(MANIFEST_FILE), manifest_data).await {
        discard_staging().await;
        return Err(InstallError::new(subject, replace, e));
    }

    // Where the mod came from goes in with the new files, so the swap
    // below moves them in together and a crash after it never leaves the
    // mod without an origin record. A replace records it afresh, from the
    // file's Nexus Mods download name (as a new install of the file would);
    // an update keeps the old record, which its caller then brings up to
    // date with the new version.
    if let Err(e) = stage_origin(&old_dir, &staging_dir, &manifest, archive_path, same_id_only).await {
        discard_staging().await;
        return Err(InstallError::new(subject, replace, e));
    }
    if let Err(e) = sync_staged_tree(&staging_dir).await {
        discard_staging().await;
        return Err(InstallError::new(subject, replace, e));
    }

    // What the profiles need once the new version is in: entries moved
    // from DDMM's own ID to the author's (see below), then every entry of
    // the mod fitted to the new manifest.json.
    let follow_up = FollowUp {
        guid: final_guid,
        moved_from: (final_guid != existing_guid && is_local_generated(&old_mod.manifest)).then_some(existing_guid),
        reset_in: Vec::new(),
    };

    log::info!("Swapping in updated content for mod {{{}}}...", final_guid);
    let backup_dir = mods_root.join(format!("{}{}", mod_folder::UPDATE_BACKUP_PREFIX, Uuid::new_v4()));
    // Note where the old version belongs, and what the profiles need after
    // the swap, before setting it aside: if DDMM is closed (or crashes)
    // mid-swap, the next start puts the old version back instead of
    // guessing; if it stops after the swap, the next start finishes the
    // profiles (see `finish_follow_ups`).
    let record = mod_folder::backup_record_path(&backup_dir);
    if let Err(e) = write_backup_record(&record, &old_dir, false, Some(&follow_up)).await {
        discard_staging().await;
        return Err(InstallError::new(subject, replace, e));
    }

    if crash_point(CrashPoint::BeforeSetAside) {
        return Err(InstallError::new(subject, replace, anyhow::anyhow!("simulated crash")));
    }
    if let Err(e) = crate::fs_util::move_path(&old_dir, &backup_dir).await {
        discard_staging().await;
        let _ = tokio::fs::remove_file(&record).await;
        return Err(InstallError::new(subject, replace, e));
    }
    if crash_point(CrashPoint::BeforeMoveIn) {
        return Err(InstallError::new(subject, replace, anyhow::anyhow!("simulated crash")));
    }

    if let Err(e) = crate::fs_util::move_path(&staging_dir, &old_dir).await {
        // Roll back: put the old content back where it was.
        match crate::fs_util::move_path(&backup_dir, &old_dir).await {
            Ok(()) => {
                let _ = tokio::fs::remove_file(&record).await;
            }
            // The record stays, so the next start restores it.
            Err(rollback) => log::error!("Couldn't put {:?} back after a failed update: {:#}", old_dir, rollback),
        }
        discard_staging().await;
        return Err(InstallError::new(subject, replace, e));
    }

    // The staging folder is the mod's folder now.
    let _ = tokio::fs::remove_file(&staging_record).await;

    if crash_point(CrashPoint::BeforeSwapNoted) {
        return Err(InstallError::new(subject, replace, anyhow::anyhow!("simulated crash")));
    }
    // The update is done: note that, so the old version is never put back
    // over (or next to) the new one.
    let noted = if fail_point(FailPoint::SwapNote) {
        Err(anyhow::anyhow!("simulated failure"))
    } else {
        write_backup_record(&record, &old_dir, true, Some(&follow_up)).await
    };
    if crash_point(CrashPoint::BeforeBackupRemoved) {
        return Err(InstallError::new(subject, replace, anyhow::anyhow!("simulated crash")));
    }
    match noted {
        // The record itself stays until the profiles are written.
        Ok(()) => {
            if let Err(e) = mod_folder::remove_mod_folder(&mods_root, &backup_dir).await {
                // E.g. a file in it still open on Windows: it stays (hidden,
                // never loaded) with its record, and is deleted along with
                // the mod.
                log::warn!("Couldn't remove the previous version of the updated mod yet: {:#}", e);
            }
        }
        // The old version stays (hidden, never loaded): without it, a crash
        // before the profiles are written would leave a record that says
        // the swap never happened and nothing to tell otherwise, and the
        // next start would report the update as undone. With it, the next
        // start sees the new version in place (`recover_update_backup`);
        // writing the profiles below marks it swapped (`finish_record`).
        Err(e) => log::warn!("Couldn't note the finished update in {:?}; keeping the previous version for now: {:#}", record, e),
    }

    let mut new_mod = Mod {
        manifest,
        directory: old_dir,
        sources: Vec::new(),
    };

    if let Err(e) = new_mod.normalize_paths().await {
        log::error!("Path normalization failed: {}", e);
    }
    new_mod.resolve_sources().await;

    mods.retain(|m| m.guid() != existing_guid);
    mods.push(new_mod.clone());

    // An ID DDMM generated, replaced by the author's (the mod was installed
    // before DDMM found manifest.json inside a zipped folder): its profile
    // entries follow it, keeping on/off and their place.
    if let Some(old) = follow_up.moved_from {
        state.record_guid_rename(old, final_guid);
    }
    if crash_point(CrashPoint::BeforeProfiles) {
        return Err(InstallError::new(subject, replace, anyhow::anyhow!("simulated crash")));
    }
    match apply_follow_up(&state.base_path, Some(&record), &follow_up, &new_mod.manifest).await {
        Ok(_) if crash_point(CrashPoint::BeforeRecordRemoved) => {
            return Err(InstallError::new(subject, replace, anyhow::anyhow!("simulated crash")));
        }
        Ok(_) => finish_record(&record).await,
        // The record stays: the next start writes them.
        Err(e) => log::error!("Couldn't update the profile entries of {{{final_guid}}} in profiles.json: {e:#}"),
    }

    log::info!("Mod {{{}}} updated successfully.", new_mod.guid());
    Ok((new_mod, warning))
}

/// Put DDMM's mod storage back in order after an update that didn't finish
/// (DDMM closed or crashed mid-swap, or a file still in use on Windows kept
/// the old version from being deleted). Runs once, before the mods are
/// first read.
///
/// Keeping data always wins over tidiness: a leftover folder is deleted
/// only when an identical copy of it (same files, byte for byte) is in
/// place as a visible mod. Otherwise:
///
/// - `.update-backup-<id>` (the old version set aside during an update) is
///   put back into its recorded folder when the swap never happened and
///   that folder is missing; restored under a free name when nothing
///   visible has its ID; and otherwise left where it is (hidden, not
///   loaded) -- e.g. when the update finished, when the mod was deleted
///   since, or when restoring it would list two mods with one ID;
/// - `.update-<id>` (an update's staging copy) is left where it is;
/// - `.adopt-<id>` (a wrapped folder in the storage being set up where it
///   is, see [`crate::mod_root::unwrap_in_place`]) is put back, or
///   finished, by its record, and otherwise left where it is;
/// - any other dot-folder with a manifest.json (a mod installed by an
///   older version from a file whose name started with a dot) is renamed
///   to a visible name so it keeps showing up. When that rename fails it
///   is returned, and the caller loads it under its dot-name anyway.
///
/// Order, each step relying on the ones before it:
///
/// 1. in-place setups (`.adopt-<id>`), before anything else looks at the
///    storage's folders: putting one back recreates a visible mod folder
///    (`mods/<name>`) that the rest of the sweep -- an update backup
///    waiting for its folder, in particular -- must see as taken, or it
///    could restore into that name. It only ever touches its own `.adopt-`
///    folder and the folder named in its record, so nothing later can be
///    in its way; it never involves an update's record;
/// 2. unfinished deletes (`.delete-<id>`);
/// 3. update backups (put back or kept);
/// 4. update staging copies;
/// 5. what those updates left for profiles.json ([`finish_follow_ups`]):
///    it needs the backups dealt with first, to know which version is in
///    place;
/// 6. update records left without a backup (never one with a follow-up
///    still to do);
/// 7. dot-named mods.
///
/// Problems are logged, never fatal: the mod list still loads. What the
/// user should know -- what it finished or undid, and what it had to leave
/// as it is -- is also collected as [`Recovered::notices`].
pub(crate) async fn recover_leftover_folders(mods_root: &Path) -> Recovered {
    let mut notices = Notices::default();
    // 1. In-place setups; see the order above.
    let root = mods_root.to_path_buf();
    match tokio::task::spawn_blocking(move || crate::mod_root::recover_in_place_unwraps(&root)).await {
        Ok(left) if !left.is_empty() => {
            log::error!("{} hidden in-place setup folder(s) left in the mod storage: {:?}", left.len(), left);
            for stage in left {
                let notice = StartupNotice::new(NoticeKind::AdoptLeft).folder(&stage);
                notices.push(match crate::mod_root::in_place_folder_name(&stage) {
                    Some(name) => notice.named(name),
                    None => notice,
                });
            }
        }
        Ok(_) => {}
        Err(e) => log::warn!("Couldn't check for unfinished in-place setups: {e}"),
    }
    let Ok(mut entries) = tokio::fs::read_dir(mods_root).await else { return Recovered { notices, ..Recovered::default() } };
    let mut backups = Vec::new();
    let mut staging = Vec::new();
    let mut hidden_mods = Vec::new();
    let mut records = Vec::new();
    let mut pending_deletes = Vec::new();
    let mut pending_records = Vec::new();
    let mut staging_records = Vec::new();
    while let Ok(Some(entry)) = entries.next_entry().await {
        let Some(name) = entry.file_name().to_str().map(str::to_string) else { continue };
        if !name.starts_with('.') {
            continue;
        }
        let path = entry.path();
        let is_dir = tokio::fs::symlink_metadata(&path).await.map(|m| m.is_dir()).unwrap_or(false);
        if let Some(rest) = name.strip_prefix(mod_folder::PENDING_DELETE_PREFIX) {
            if is_dir && Uuid::parse_str(rest).is_ok() {
                pending_deletes.push(path);
                continue;
            }
            if !is_dir
                && rest
                    .strip_suffix(mod_folder::PENDING_DELETE_RECORD_SUFFIX)
                    .is_some_and(|id| Uuid::parse_str(id).is_ok())
            {
                pending_records.push(path);
                continue;
            }
        }
        if let Some(rest) = name.strip_prefix(mod_folder::UPDATE_BACKUP_PREFIX) {
            if is_dir && Uuid::parse_str(rest).is_ok() {
                backups.push(path);
            } else if !is_dir
                && rest
                    .strip_suffix(mod_folder::UPDATE_BACKUP_RECORD_SUFFIX)
                    .is_some_and(|id| Uuid::parse_str(id).is_ok())
            {
                records.push(path);
            }
        } else if let Some(rest) = name.strip_prefix(mod_folder::UPDATE_STAGING_PREFIX) {
            if is_dir && Uuid::parse_str(rest).is_ok() {
                staging.push(path);
            } else if !is_dir
                && rest
                    .strip_suffix(mod_folder::UPDATE_STAGING_RECORD_SUFFIX)
                    .is_some_and(|id| Uuid::parse_str(id).is_ok())
            {
                staging_records.push(path);
            }
        } else if let Some(rest) = name.strip_prefix(mod_folder::UNWRAP_PREFIX) {
            // An archive unpacked for an install that didn't finish: only
            // a copy of the archive, never anything else.
            if is_dir && Uuid::parse_str(rest).is_ok() {
                match mod_folder::remove_mod_folder(mods_root, &path).await {
                    Ok(()) => log::info!("Removed {:?}, left by an install that didn't finish.", path),
                    Err(e) => log::warn!("Couldn't remove {:?} yet: {:#}", path, e),
                }
            }
        } else if name.starts_with(mod_folder::IN_PLACE_UNWRAP_PREFIX) {
            // The user's own files: handled above, never loaded or renamed.
        } else if is_dir && path.join(MANIFEST_FILE).is_file() {
            hidden_mods.push((path, name));
        }
    }

    // 2. Deletes that couldn't finish (a file was in use): only folders DDMM
    // set aside itself, i.e. with their record, are deleted.
    for dir in pending_deletes {
        if tokio::fs::symlink_metadata(mod_folder::pending_delete_record_path(&dir)).await.is_err() {
            log::warn!("Keeping {:?}: it has no record saying DDMM set it aside for deleting.", dir);
            notices.push(named_by_manifest(StartupNotice::new(NoticeKind::DeleteKept).folder(&dir), &dir).await);
            continue;
        }
        match finish_pending_delete(mods_root, &dir).await {
            Ok(()) => log::info!("Finished deleting {:?} (a removed mod's files that were in use).", dir),
            Err(e) => log::warn!("Couldn't finish deleting {:?} yet: {:#}", dir, e),
        }
    }
    for record in pending_records {
        let dir = record.with_file_name(
            record
                .file_name()
                .unwrap_or_default()
                .to_string_lossy()
                .trim_end_matches(mod_folder::PENDING_DELETE_RECORD_SUFFIX),
        );
        if tokio::fs::symlink_metadata(&dir).await.is_err() && mod_folder::ensure_mod_folder(mods_root, &record).is_ok() {
            let _ = tokio::fs::remove_file(&record).await;
        }
    }
    // 3.-7.: see the order above.
    for backup in backups {
        let name = backup_name(mods_root, &backup).await;
        match recover_update_backup(mods_root, &backup).await {
            Ok(BackupOutcome::Restored(to)) => notices.push(StartupNotice::new(NoticeKind::UpdateUndone).named(name).folder(to)),
            Ok(BackupOutcome::RestoredElsewhere(to)) => {
                notices.push(StartupNotice::new(NoticeKind::BackupRestored).named(name).folder(to))
            }
            Ok(BackupOutcome::Stuck) => notices.push(StartupNotice::new(NoticeKind::BackupKept).named(name).folder(&backup)),
            Ok(BackupOutcome::Removed | BackupOutcome::Replaced) => {}
            Err(e) => {
                log::error!("Couldn't recover {:?}, left as it is: {:#}", backup, e);
                notices.push(StartupNotice::new(NoticeKind::BackupKept).named(name).folder(&backup));
            }
        }
    }
    for dir in staging {
        let record = mod_folder::staging_record_path(&dir);
        let recorded = tokio::fs::symlink_metadata(&record).await.is_ok_and(|m| m.is_file());
        if recorded && mod_folder::ensure_mod_folder(mods_root, &dir).is_ok() {
            // DDMM's own extraction, and the swap never happened (it would
            // have renamed this folder away): only a copy of an archive.
            match mod_folder::remove_mod_folder(mods_root, &dir).await {
                Ok(()) => {
                    log::info!("Removed {:?}, the new files of an update that didn't finish.", dir);
                    let _ = tokio::fs::remove_file(&record).await;
                }
                Err(e) => log::warn!("Couldn't remove {:?} yet (the next start tries again): {:#}", dir, e),
            }
            continue;
        }
        // Left by an older version, without a record: kept unless it's an
        // identical copy of the installed mod.
        if !remove_if_duplicate(mods_root, &dir, None).await && tokio::fs::symlink_metadata(&dir).await.is_ok() {
            notices.push(named_by_manifest(StartupNotice::new(NoticeKind::StagingKept).folder(&dir), &dir).await);
        }
    }
    for record in staging_records {
        // Its folder was swapped in or removed: the record is moot.
        let dir = record.with_file_name(
            record
                .file_name()
                .unwrap_or_default()
                .to_string_lossy()
                .trim_end_matches(mod_folder::UPDATE_STAGING_RECORD_SUFFIX),
        );
        if tokio::fs::symlink_metadata(&dir).await.is_err() && mod_folder::ensure_mod_folder(mods_root, &record).is_ok() {
            let _ = tokio::fs::remove_file(&record).await;
        }
    }
    let renames = finish_follow_ups(mods_root, &records, &mut notices).await;
    for record in records {
        let backup = backup_of_record(&record);
        // One whose follow-up couldn't be done yet stays for the next start.
        if read_backup_record(mods_root, &record).await.follow_up.is_some() {
            continue;
        }
        if tokio::fs::symlink_metadata(&backup).await.is_err() && mod_folder::ensure_mod_folder(mods_root, &record).is_ok() {
            let _ = tokio::fs::remove_file(&record).await;
        }
    }
    let mut still_hidden = Vec::new();
    for (dir, name) in hidden_mods {
        let target = mods_root.join(mod_folder::free_folder_name(mods_root, &name, &|_| false));
        match crate::fs_util::move_path(&dir, &target).await {
            Ok(()) => log::info!("Renamed the mod folder {:?} to {:?} so it stays visible.", dir, target),
            Err(e) => {
                log::error!(
                    "Couldn't rename the mod folder {:?} to a name without a leading dot; loading it as it is: {:#}",
                    dir, e
                );
                still_hidden.push(dir);
            }
        }
    }
    Recovered { still_hidden, renames, notices }
}

/// What [`recover_leftover_folders`] hands back.
#[derive(Debug, Default)]
pub(crate) struct Recovered {
    /// Dot-named mod folders that couldn't be renamed: load them anyway.
    pub still_hidden: Vec<PathBuf>,
    /// Mods whose ID an unfinished update changed (old, new): their
    /// entries are moved in profiles.json, or will be on a later start.
    pub renames: Vec<(Uuid, Uuid)>,
    /// What the user should be told (see [`crate::startup_notices`]).
    pub notices: Notices,
}

/// What [`recover_update_backup`] did with one backup.
#[derive(Debug, PartialEq, Eq)]
enum BackupOutcome {
    /// Deleted: an identical copy is in place.
    Removed,
    /// Kept hidden: the version a finished update replaced (or of a mod
    /// deleted since). Nothing to tell.
    Replaced,
    /// Put back into the folder it was set aside from: the update didn't
    /// finish.
    Restored(PathBuf),
    /// Put back under a free name (no record, or its folder taken since,
    /// and its ID not installed).
    RestoredElsewhere(PathBuf),
    /// Kept hidden, though it may be the only copy: nowhere safe to put it.
    Stuck,
}

/// The name of the mod in the backup folder `backup`, for a notice.
async fn backup_name(mods_root: &Path, backup: &Path) -> String {
    if let Some(m) = read_manifest_quietly(&backup.join(MANIFEST_FILE)).await {
        return manifest_name(&m).to_string();
    }
    read_backup_record(mods_root, &mod_folder::backup_record_path(backup))
        .await
        .folder
        .unwrap_or_else(|| folder_name(backup))
}

/// `notice` with the name and ID of the mod in `dir`, if its manifest.json
/// can be read.
async fn named_by_manifest(notice: StartupNotice, dir: &Path) -> StartupNotice {
    match read_manifest_quietly(&dir.join(MANIFEST_FILE)).await {
        Some(m) => notice.named(manifest_name(&m)).guid(manifest_guid(&m)),
        None => notice,
    }
}

/// What an update backup's record file says.
#[derive(Debug, Default)]
struct BackupRecord {
    /// The folder the backed-up version came from.
    folder: Option<String>,
    /// Set once the new version was moved in: the update finished, and the
    /// backup is only the version it replaced.
    swapped: bool,
    /// What profiles.json still needs once the new version is in; gone
    /// once it's written.
    follow_up: Option<FollowUp>,
}

/// What an update or replace still has to do to profiles.json after its
/// swap: move the entries of `moved_from` (an ID DDMM generated, replaced
/// by the author's) over to `guid`, and fit every entry of `guid` to the
/// mod's new manifest.json (see `profiles::migrate_saved_profiles`). Kept
/// in the backup record until profiles.json is written, so that a crash
/// in between is finished on the next start (see [`finish_follow_ups`]).
#[derive(Debug, Clone, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
pub(crate) struct FollowUp {
    pub guid: Uuid,
    pub moved_from: Option<Uuid>,
    /// The profiles in which writing it resets option choices, noted in
    /// the record before profiles.json is written: a crash after the write
    /// still tells the user on the next start (when the entries already
    /// fit, and nothing would say they were reset).
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub reset_in: Vec<String>,
}

/// Do `follow_up` for the mod whose new manifest is `manifest`: one write
/// of profiles.json (durable), and nothing when no profile lists the mod.
/// Doing it again changes nothing.
/// Returns the profiles in which option choices that no longer fit were
/// reset -- by this write, or by an earlier one the record (`record`, if
/// any) noted before it crashed.
async fn apply_follow_up(base_path: &Path, record: Option<&Path>, follow_up: &FollowUp, manifest: &Manifest) -> anyhow::Result<Vec<String>> {
    let from = follow_up.moved_from.unwrap_or(follow_up.guid);
    let plan = crate::commands::profiles::plan_saved_profiles_migration(base_path, from, follow_up.guid, manifest).await?;
    let mut reset_in = follow_up.reset_in.clone();
    for name in &plan.migrated.reset_in {
        if !reset_in.contains(name) {
            reset_in.push(name.clone());
        }
    }
    if let (Some(record), true) = (record, reset_in != follow_up.reset_in) {
        if let Err(e) = note_reset_in(record, &reset_in).await {
            log::warn!("Couldn't note the reset options in {:?}: {:#}", record, e);
        }
    }
    let migrated = plan.write().await?;
    let n = migrated.entries;
    match follow_up.moved_from {
        Some(old) if n > 0 => log::info!("Moved the profile entries of {{{old}}} to {{{}}} and fitted {n} to its manifest.", follow_up.guid),
        _ if n > 0 => log::info!("Fitted {n} profile entr(ies) of {{{}}} to its new manifest.", follow_up.guid),
        _ => {}
    }
    if !migrated.reset_in.is_empty() {
        log::info!("Option choices of {{{}}} reset to the defaults in: {:?}", follow_up.guid, migrated.reset_in);
    }
    Ok(reset_in)
}

/// Note `reset_in` in the follow-up of the backup record `record` (see
/// [`FollowUp::reset_in`]).
async fn note_reset_in(record: &Path, reset_in: &[String]) -> anyhow::Result<()> {
    let mut value: serde_json::Value = serde_json::from_slice(&tokio::fs::read(record).await?)?;
    let Some(follow_up) = value.get_mut("follow_up").and_then(|f| f.as_object_mut()) else { return Ok(()) };
    follow_up.insert("reset_in".into(), serde_json::json!(reset_in));
    write_record_value(record, value).await
}

/// The follow-up in the backup record `record` is done (or moot): drop it
/// from the record, or the whole record when its backup folder is gone. A
/// record kept is marked swapped as well: a follow-up is only ever dropped
/// with a backup still there once the new version is in place, and the
/// backup must then never be put back (next to the new version, if the
/// update changed the mod's ID) -- even if marking it failed before.
async fn finish_record(record: &Path) {
    let backup = backup_of_record(record);
    let result = if tokio::fs::symlink_metadata(&backup).await.is_err() {
        match tokio::fs::remove_file(record).await {
            Err(e) if e.kind() != std::io::ErrorKind::NotFound => Err(anyhow::Error::from(e)),
            _ => Ok(()),
        }
    } else {
        let mut value = match tokio::fs::read(record).await.ok().and_then(|d| serde_json::from_slice::<serde_json::Value>(&d).ok()) {
            Some(serde_json::Value::Object(map)) => map,
            _ => return,
        };
        value.remove("follow_up");
        value.insert("swapped".into(), serde_json::Value::Bool(true));
        write_record_value(record, serde_json::Value::Object(value)).await
    };
    if let Err(e) = result {
        log::warn!("Couldn't tidy up {:?} (the next start does): {:#}", record, e);
    }
}

/// The backup folder a record file belongs to.
fn backup_of_record(record: &Path) -> PathBuf {
    record.with_file_name(
        record
            .file_name()
            .unwrap_or_default()
            .to_string_lossy()
            .trim_end_matches(mod_folder::UPDATE_BACKUP_RECORD_SUFFIX),
    )
}

/// Finish what updates and replaces that didn't finish left for
/// profiles.json (DDMM closed or crashed between the swap and writing the
/// profiles): runs on the next start, after the backups were dealt with
/// (see [`recover_update_backup`]), and before the profiles are read (the
/// page's `load_profiles` waits for the mod list).
///
/// For each record with a follow-up:
/// - the swap finished (the mod's folder holds the new version): its
///   entries are moved to the new ID and fitted, then the follow-up is
///   dropped -- the full new state;
/// - it didn't (the old version is back in place): the follow-up is
///   dropped, profiles.json is left as it was -- the old state.
///
/// A follow-up that can't be done now (profiles.json in use, or the new
/// version's manifest.json unreadable -- e.g. cut short by a power loss)
/// stays for the start after. Returns the ID changes of the finished swaps
/// (done or still to do), for this session's renames; what the user should
/// know goes to `notices`.
async fn finish_follow_ups(mods_root: &Path, records: &[PathBuf], notices: &mut Notices) -> Vec<(Uuid, Uuid)> {
    let mut renames = Vec::new();
    let Some(base_path) = mods_root.parent() else { return renames };
    for record in records {
        if crash_point(CrashPoint::RecoveryBeforeProfiles) {
            return renames;
        }
        let parsed = read_backup_record(mods_root, record).await;
        let Some(follow_up) = parsed.follow_up else { continue };
        if !parsed.swapped && tokio::fs::symlink_metadata(backup_of_record(record)).await.is_ok() {
            // The old version is still set aside (it couldn't be put back
            // this time): left for the next start.
            continue;
        }
        let folder = match (&parsed.folder, parsed.swapped) {
            (Some(folder), true) => mods_root.join(folder),
            _ => {
                log::info!("{:?}: the update didn't finish, so the profiles stay as they were.", record);
                finish_record(record).await;
                if let (Some(folder), false) = (&parsed.folder, parsed.swapped) {
                    let dir = mods_root.join(folder);
                    let notice = StartupNotice::new(NoticeKind::UpdateUndone).named(folder.as_str()).folder(&dir);
                    notices.push(named_by_manifest(notice, &dir).await);
                }
                continue;
            }
        };
        if tokio::fs::symlink_metadata(&folder).await.is_err() {
            log::info!("{:?}: the updated mod's folder is gone (deleted since); the profiles stay as they are.", record);
            finish_record(record).await;
            continue;
        }
        let Some(manifest) = read_manifest_quietly(&folder.join(MANIFEST_FILE)).await else {
            log::error!(
                "{:?}: the updated mod's manifest.json can't be read; its profile entries are left for the next start.",
                folder
            );
            notices.push(StartupNotice::new(NoticeKind::UpdatePending).named(folder_name(&folder)).guid(follow_up.guid).folder(&folder));
            continue;
        };
        if manifest_guid(&manifest) != follow_up.guid {
            log::info!("{:?} holds another mod now; the profiles stay as they are.", folder);
            finish_record(record).await;
            continue;
        }
        let mut follow_up = follow_up;
        if let Some(old) = follow_up.moved_from {
            // An old ID that's a mod's again keeps its entries.
            if visible_folders_with_guid(mods_root, old).await.is_empty() {
                renames.push((old, follow_up.guid));
            } else {
                follow_up.moved_from = None;
            }
        }
        let name = manifest_name(&manifest).to_string();
        match apply_follow_up(base_path, Some(record), &follow_up, &manifest).await {
            Ok(_) if crash_point(CrashPoint::RecoveryBeforeRecordDropped) => return renames,
            Ok(reset_in) => {
                log::info!("Finished the profiles of {{{}}} after an update that didn't finish.", follow_up.guid);
                finish_record(record).await;
                notices.push(StartupNotice::new(NoticeKind::UpdateFinished).named(name.as_str()).guid(follow_up.guid).folder(&folder));
                if !reset_in.is_empty() {
                    notices.push(StartupNotice::new(NoticeKind::OptionsReset).named(name.as_str()).guid(follow_up.guid).profiles(reset_in));
                }
            }
            Err(e) => {
                log::error!("Couldn't finish the profiles of {{{}}} yet (the next start tries again): {e:#}", follow_up.guid);
                notices.push(StartupNotice::new(NoticeKind::ProfilesRetry).named(name.as_str()).guid(follow_up.guid));
            }
        }
    }
    renames
}

/// Where a test stops an update or replace, as if DDMM crashed there.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum CrashPoint {
    /// The record is written; nothing moved yet.
    BeforeSetAside,
    /// The old version is set aside; the new one not moved in.
    BeforeMoveIn,
    /// The new version is in; the record doesn't say so yet.
    BeforeSwapNoted,
    /// The record says so; the old version isn't deleted yet.
    BeforeBackupRemoved,
    /// Only profiles.json is left.
    BeforeProfiles,
    /// profiles.json is written; the record not dropped yet.
    BeforeRecordRemoved,
    /// Recovery on the next start: before it writes profiles.json.
    RecoveryBeforeProfiles,
    /// Recovery: profiles.json written, the record not dropped yet.
    RecoveryBeforeRecordDropped,
}

#[cfg(test)]
thread_local! {
    pub(crate) static CRASH_AT: std::cell::Cell<Option<CrashPoint>> = const { std::cell::Cell::new(None) };
    pub(crate) static FAIL_AT: std::cell::Cell<Option<FailPoint>> = const { std::cell::Cell::new(None) };
}

/// Where a test makes one step fail (and DDMM carry on), as a full disk or
/// a file in use would.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum FailPoint {
    /// An update can't write "swapped" to its record.
    SwapNote,
    /// Reading the mod list fails after the recovery.
    ModRead,
}

#[cfg(test)]
fn fail_point(at: FailPoint) -> bool {
    FAIL_AT.with(|c| c.get()) == Some(at)
}

#[cfg(not(test))]
#[inline(always)]
fn fail_point(_: FailPoint) -> bool {
    false
}

#[cfg(test)]
fn crash_point(at: CrashPoint) -> bool {
    CRASH_AT.with(|c| c.get()) == Some(at)
}

#[cfg(not(test))]
#[inline(always)]
fn crash_point(_: CrashPoint) -> bool {
    false
}

/// Put the origin record the new version should start with into the
/// staged folder `staging_dir` (see [`install_update_steps`]): for a
/// replace (`fresh`), the one a new install of `archive_path` would get
/// from its Nexus Mods download name (if any); for an update, the old
/// version's (in `old_dir`), if it has one.
async fn stage_origin(old_dir: &Path, staging_dir: &Path, manifest: &Manifest, archive_path: &Path, fresh: bool) -> anyhow::Result<()> {
    if fresh {
        let mut staged = Mod { manifest: manifest.clone(), directory: staging_dir.to_path_buf(), sources: Vec::new() };
        staged.resolve_sources().await;
        let file_name = archive_path.file_name().and_then(|n| n.to_str()).unwrap_or_default();
        if let Some(sidecar) = nexus_sidecar_from_file_name(&staged, file_name, true).await {
            sources::save_origin_sidecar(staging_dir, &sidecar).await?;
        }
    } else if let Some(mut sidecar) = sources::load_origin_sidecar(old_dir).await {
        // What the old version's record says about where it came from; not
        // what's tied to that version (see `OriginSidecar`).
        sidecar.skipped_versions.clear();
        sidecar.imported_archive = None;
        sources::save_origin_sidecar(staging_dir, &sidecar).await?;
    }
    Ok(())
}

/// Get the staged tree `dir` onto the disk before it's swapped in, so a
/// power loss after the swap can't leave the new version with empty
/// files (manifest.json above all). manifest.json must sync; the rest is
/// best effort (a file that can't be opened for it is logged).
async fn sync_staged_tree(dir: &Path) -> anyhow::Result<()> {
    fn sync_file(file: &Path) -> std::io::Result<()> {
        std::fs::OpenOptions::new().write(true).open(file)?.sync_all()
    }
    // A folder's entries (Unix; NTFS journals them itself).
    fn sync_dir(dir: &Path) {
        #[cfg(unix)]
        if let Ok(d) = std::fs::File::open(dir) {
            let _ = d.sync_all();
        }
        #[cfg(not(unix))]
        let _ = dir;
    }
    fn walk(dir: &Path) {
        let Ok(entries) = std::fs::read_dir(dir) else { return };
        for entry in entries.flatten() {
            let path = entry.path();
            match entry.file_type() {
                Ok(t) if t.is_dir() => {
                    walk(&path);
                    sync_dir(&path);
                }
                Ok(t) if t.is_file() => {
                    if let Err(e) = sync_file(&path) {
                        log::warn!("Couldn't sync {:?} to disk: {}", path, e);
                    }
                }
                _ => {}
            }
        }
    }
    let dir = dir.to_path_buf();
    tokio::task::spawn_blocking(move || {
        walk(&dir);
        sync_file(&dir.join(MANIFEST_FILE)).with_context(|| format!("couldn't write {:?} to disk", dir.join(MANIFEST_FILE)))?;
        sync_dir(&dir);
        Ok(())
    })
    .await?
}

async fn read_backup_record(mods_root: &Path, record: &Path) -> BackupRecord {
    let Ok(data) = tokio::fs::read(record).await else { return BackupRecord::default() };
    let Ok(value) = serde_json::from_slice::<serde_json::Value>(&data) else { return BackupRecord::default() };
    BackupRecord {
        folder: value
            .get("folder")
            .and_then(|f| f.as_str())
            .map(str::to_string)
            .filter(|n| !n.is_empty() && !n.starts_with('.') && mod_folder::ensure_mod_folder(mods_root, &mods_root.join(n)).is_ok()),
        swapped: value.get("swapped").and_then(|v| v.as_bool()).unwrap_or(false),
        follow_up: value.get("follow_up").and_then(|f| serde_json::from_value(f.clone()).ok()),
    }
}

/// Write an update backup's record (see [`BackupRecord`]): whole or not at
/// all, and on disk before this returns, so that what's moved after it is
/// never ahead of its record.
async fn write_backup_record(record: &Path, folder: &Path, swapped: bool, follow_up: Option<&FollowUp>) -> anyhow::Result<()> {
    let mut data = serde_json::json!({
        "folder": folder.file_name().map(|n| n.to_string_lossy().into_owned()),
        "swapped": swapped,
    });
    if let Some(f) = follow_up {
        data["follow_up"] = serde_json::to_value(f)?;
    }
    write_record_value(record, data).await
}

async fn write_record_value(record: &Path, data: serde_json::Value) -> anyhow::Result<()> {
    let record = record.to_path_buf();
    tokio::task::spawn_blocking(move || crate::fs_util::replace_file_durably_blocking(&record, data.to_string().as_bytes())).await?
}

/// Delete the leftover `dir` only if one of the visible mod folders
/// (`candidates`, or else every visible folder whose manifest has the same
/// ID as `dir`'s) holds an identical copy of it. Returns whether it did.
async fn remove_if_duplicate(mods_root: &Path, dir: &Path, candidates: Option<Vec<PathBuf>>) -> bool {
    let candidates = match candidates {
        Some(c) => c,
        None => match read_manifest_quietly(&dir.join(MANIFEST_FILE)).await {
            Some(m) => visible_folders_with_guid(mods_root, manifest_guid(&m)).await,
            None => Vec::new(),
        },
    };
    for candidate in candidates {
        let (a, b) = (dir.to_path_buf(), candidate.clone());
        let same = tokio::task::spawn_blocking(move || same_tree(&a, &b)).await.unwrap_or(false);
        if same {
            match mod_folder::remove_mod_folder(mods_root, dir).await {
                Ok(()) => {
                    log::info!("Removed {:?}: an identical copy is installed as {:?}.", dir, candidate);
                    return true;
                }
                Err(e) => {
                    log::warn!("Couldn't remove {:?}: {:#}", dir, e);
                    return false;
                }
            }
        }
    }
    log::info!("Keeping {:?} (left over from an update that didn't finish): no identical copy is installed.", dir);
    false
}

/// Whether the trees `a` and `b` hold the same folders and files, byte for
/// byte (symlinks are never followed and count as a difference). Any error
/// counts as "not the same".
fn same_tree(a: &Path, b: &Path) -> bool {
    fn walk(root: &Path, dir: &Path, out: &mut Vec<(PathBuf, bool, u64)>) -> std::io::Result<()> {
        for entry in std::fs::read_dir(dir)? {
            let entry = entry?;
            let meta = std::fs::symlink_metadata(entry.path())?;
            let rel = entry.path().strip_prefix(root).map_err(std::io::Error::other)?.to_path_buf();
            if meta.file_type().is_symlink() {
                return Err(std::io::Error::other("symlink"));
            } else if meta.is_dir() {
                out.push((rel, true, 0));
                walk(root, &entry.path(), out)?;
            } else {
                out.push((rel, false, meta.len()));
            }
        }
        Ok(())
    }
    fn same_file(a: &Path, b: &Path) -> std::io::Result<bool> {
        use std::io::Read;
        let (mut fa, mut fb) = (std::fs::File::open(a)?, std::fs::File::open(b)?);
        let (mut ba, mut bb) = (vec![0u8; 1 << 16], vec![0u8; 1 << 16]);
        loop {
            let n = fa.read(&mut ba)?;
            if n == 0 {
                return Ok(fb.read(&mut bb[..1])? == 0);
            }
            fb.read_exact(&mut bb[..n])?;
            if ba[..n] != bb[..n] {
                return Ok(false);
            }
        }
    }
    let (mut ta, mut tb) = (Vec::new(), Vec::new());
    if walk(a, a, &mut ta).is_err() || walk(b, b, &mut tb).is_err() {
        return false;
    }
    ta.sort();
    tb.sort();
    ta == tb
        && ta
            .iter()
            .filter(|(_, is_dir, _)| !is_dir)
            .all(|(rel, _, _)| same_file(&a.join(rel), &b.join(rel)).unwrap_or(false))
}

/// One `.update-backup-<id>` folder; see [`recover_leftover_folders`].
async fn recover_update_backup(mods_root: &Path, backup: &Path) -> anyhow::Result<BackupOutcome> {
    mod_folder::ensure_mod_folder(mods_root, backup)?;
    let record_file = mod_folder::backup_record_path(backup);
    let mut record = read_backup_record(mods_root, &record_file).await;
    let backup_manifest = read_manifest_quietly(&backup.join(MANIFEST_FILE)).await;
    let backup_guid = backup_manifest.as_ref().map(manifest_guid);

    // Stopped right after the new version was moved in, before the record
    // said so: its folder has the new version (with the ID the record
    // expects), so the update did finish. Without this, an update that
    // changed the mod's ID would bring the old version back next to it.
    if let (false, Some(follow_up), Some(folder)) = (record.swapped, &record.follow_up, &record.folder) {
        let installed = read_manifest_quietly(&mods_root.join(folder).join(MANIFEST_FILE)).await;
        if installed.as_ref().map(manifest_guid) == Some(follow_up.guid) {
            write_backup_record(&record_file, &mods_root.join(folder), true, Some(follow_up)).await?;
            record.swapped = true;
        }
    }

    // An identical copy in place: the only case a backup is deleted.
    let same_id = match backup_guid {
        Some(guid) => visible_folders_with_guid(mods_root, guid).await,
        None => Vec::new(),
    };
    let mut candidates = same_id.clone();
    if let Some(folder) = &record.folder {
        let original = mods_root.join(folder);
        if !candidates.contains(&original) && original.is_dir() {
            candidates.push(original);
        }
    }
    if !candidates.is_empty() && remove_if_duplicate(mods_root, backup, Some(candidates)).await {
        // A finished swap's record with a follow-up stays for
        // `finish_follow_ups`, which drops it once that's done.
        if !(record.swapped && record.follow_up.is_some()) {
            let _ = tokio::fs::remove_file(&record_file).await;
        }
        return Ok(BackupOutcome::Removed);
    }

    let keep = |why: &str| log::info!("Keeping {:?} where it is (hidden, not loaded): {why}.", backup);

    if record.swapped {
        keep("it's the version an update replaced, or its mod was deleted since");
        return Ok(BackupOutcome::Replaced);
    }
    let (target, where_it_was) = match &record.folder {
        // Stopped between setting the old version aside and moving the new
        // one in: the old version is the only copy. Put it back.
        Some(folder) if tokio::fs::symlink_metadata(mods_root.join(folder)).await.is_err() => (mods_root.join(folder), true),
        _ => {
            let Some(manifest) = &backup_manifest else {
                keep("it has no manifest.json to tell which mod it is");
                return Ok(BackupOutcome::Stuck);
            };
            if !same_id.is_empty() {
                keep("another folder has a mod with the same ID, and restoring it would list two mods with one ID");
                return Ok(BackupOutcome::Stuck);
            }
            let name = record.folder.as_deref().unwrap_or(manifest_name(manifest));
            (mods_root.join(mod_folder::free_folder_name(mods_root, name, &|_| false)), false)
        }
    };

    mod_folder::ensure_mod_folder(mods_root, &target)?;
    crate::fs_util::move_path(backup, &target).await?;
    let _ = tokio::fs::remove_file(&record_file).await;
    log::info!("Restored {:?} to {:?} (left over from an update that didn't finish).", backup, target);
    Ok(if where_it_was { BackupOutcome::Restored(target) } else { BackupOutcome::RestoredElsewhere(target) })
}

/// After the mod in `mod_dir` (ID `guid`) was deleted: find what's left
/// of the versions its updates set aside (`.update-backup-*` folders), so
/// a later start never puts one back where the mod was. Returns the ones
/// to delete.
///
/// A backup belongs to the deleted mod when its record names `mod_dir`'s
/// folder -- whether that update finished or not (an unfinished one would
/// otherwise be restored into the now-missing folder) -- or, for a backup
/// without a record (older versions wrote none), when it has the deleted
/// mod's ID. Each is first marked as a finished update's leftover, which
/// is never restored; then:
///
/// - a recorded one is deleted, unless its ID belongs to a mod that's
///   still in `remaining` (the list without the deleted mod) -- that one
///   is only kept hidden;
/// - an unrecorded one is only kept hidden (it's never deleted for its ID
///   alone).
async fn claim_replaced_versions_of(mods_root: &Path, mod_dir: &Path, guid: Uuid, remaining: &[Mod]) -> Vec<PathBuf> {
    let mut to_delete = Vec::new();
    let Some(folder) = mod_dir.file_name().map(|n| n.to_string_lossy().into_owned()) else { return to_delete };
    let Ok(mut entries) = tokio::fs::read_dir(mods_root).await else { return to_delete };
    let mut backups = Vec::new();
    while let Ok(Some(entry)) = entries.next_entry().await {
        let name = entry.file_name().to_string_lossy().into_owned();
        let Some(id) = name.strip_prefix(mod_folder::UPDATE_BACKUP_PREFIX) else { continue };
        if Uuid::parse_str(id).is_ok() && entry.path().is_dir() {
            backups.push(entry.path());
        }
    }
    for backup in backups {
        let record = mod_folder::backup_record_path(&backup);
        let recorded = tokio::fs::symlink_metadata(&record).await.is_ok();
        let backup_guid = read_manifest_quietly(&backup.join(MANIFEST_FILE)).await.map(|m| manifest_guid(&m));
        let ours = if recorded {
            read_backup_record(mods_root, &record).await.folder.as_deref() == Some(folder.as_str())
        } else {
            backup_guid == Some(guid)
        };
        if !ours {
            continue;
        }
        // An unrecorded one gets a record naming no folder: a later delete
        // of a mod in that folder never claims it for deleting.
        let marked = if recorded {
            write_backup_record(&record, mod_dir, true, None).await
        } else {
            write_record_value(&record, serde_json::json!({ "folder": null, "swapped": true })).await
        };
        if let Err(e) = marked {
            log::warn!("Couldn't mark {:?} as never to be restored: {:#}", backup, e);
            continue;
        }
        let still_installed = backup_guid.is_some_and(|g| remaining.iter().any(|m| m.guid() == g));
        if recorded && !still_installed {
            to_delete.push(backup);
        } else {
            log::info!("Keeping {:?} hidden (never restored): it may belong to a mod that's still installed.", backup);
        }
    }
    to_delete
}

async fn read_manifest_quietly(file: &Path) -> Option<Manifest> {
    let data = tokio::fs::read(file).await.ok()?;
    Manifest::parse(&data, &file.to_string_lossy()).ok()
}

fn manifest_guid(manifest: &Manifest) -> Uuid {
    match manifest {
        Manifest::Legacy(m) => m.guid,
        Manifest::V1(m) => m.guid,
        Manifest::V2(m) => m.guid,
    }
}

fn manifest_name(manifest: &Manifest) -> &str {
    match manifest {
        Manifest::Legacy(m) => &m.name,
        Manifest::V1(m) => &m.name,
        Manifest::V2(m) => &m.name,
    }
}

/// The visible mod folders in `mods_root` whose manifest has `guid`.
async fn visible_folders_with_guid(mods_root: &Path, guid: Uuid) -> Vec<PathBuf> {
    let mut found = Vec::new();
    let Ok(mut entries) = tokio::fs::read_dir(mods_root).await else { return found };
    while let Ok(Some(entry)) = entries.next_entry().await {
        if is_hidden_name(&entry.file_name()) {
            continue;
        }
        if let Some(m) = read_manifest_quietly(&entry.path().join(MANIFEST_FILE)).await {
            if manifest_guid(&m) == guid {
                found.push(entry.path());
            }
        }
    }
    found
}

/// Extract `archive_path` into `staging_dir` and resolve its manifest
/// (generating a local one, with patch-layout auto-detection, if it ships
/// none), without touching anything outside `staging_dir`.
async fn stage_update(
    staging_dir: &Path,
    archive_path: &Path,
    subject: &str,
) -> Result<(Manifest, Option<String>), InstallError> {
    let archive = Archive::open(archive_path).install_step(subject, InstallStep::OpenArchive)?;
    let manifest_file = staging_dir.join(MANIFEST_FILE);
    let name = archive_path
        .file_name()
        .and_then(|n| n.to_str())
        .map(|n| crate::mod_import::display_name_from_file(n, true))
        .unwrap_or_else(|| "update".to_string());

    let (archive, mut manifest, root) = resolve_manifest(archive, name, manifest_file)
        .await
        .map_err(|e| manifest_failure(subject, e))?;

    extract_archive(archive, staging_dir.to_path_buf(), root).await.install_step(subject, InstallStep::Extract)?;

    let warning = apply_patch_layout(staging_dir, &mut manifest)
        .await
        .install_step(subject, InstallStep::FindPatchFiles)?;

    Ok((manifest, warning))
}

